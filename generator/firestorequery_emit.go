package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

// FirestoreQueryOptions selects which of the three client-supply modes the
// generated functions use. The zero value is the Context form, which is the
// default and what every run that sets nothing generates.
//
// The transactional twin takes a *firestorebind.Tx, which already carries the
// client and the tenancy, so no mode changes it.
type FirestoreQueryOptions struct {
	// ParameterAPI gives each function a leading firestorebind.Handle parameter.
	ParameterAPI bool
	// HandleResolver names a framework function answering a firestorebind.Handle
	// for one Context. ParameterAPI takes precedence over it.
	HandleResolver *SymbolPattern
}

// resolves reports whether generated bodies call a framework resolver. A
// signature that already carries the Handle resolves nothing.
func (o FirestoreQueryOptions) resolves() bool {
	return !o.ParameterAPI && o.HandleResolver != nil
}

// EmitFirestoreQueries generates one function per checked declaration, in the
// Context form.
func EmitFirestoreQueries(pkg string, plans []FirestoreQueryPlan) ([]byte, error) {
	return EmitFirestoreQueriesWithOptions(pkg, plans, FirestoreQueryOptions{})
}

// EmitFirestoreQueriesWithOptions is EmitFirestoreQueries in the mode opts
// selects.
func EmitFirestoreQueriesWithOptions(pkg string, plans []FirestoreQueryPlan, opts FirestoreQueryOptions) ([]byte, error) {
	if len(plans) == 0 {
		return nil, nil
	}
	if err := checkHandleResolver("FirestoreHandleResolver", opts.HandleResolver); err != nil {
		return nil, err
	}
	var body bytes.Buffer
	e := &firestoreQueryEmitter{opts: opts}
	for _, plan := range plans {
		if err := e.query(&body, plan); err != nil {
			return nil, err
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tinybind; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	writeFirestoreQueryImports(&out, body.Bytes())
	if opts.resolves() {
		fmt.Fprintf(&out, "import %s %q\n\n", resolverAlias, opts.HandleResolver.PackagePath)
	}
	out.Write(body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("firestorebind: format generated query: %w\n%s", err, out.String())
	}
	return formatted, nil
}

var firestoreQueryImports = []struct {
	qualifier string
	path      string
	stdlib    bool
}{
	{qualifier: "context", path: "context", stdlib: true},
	{qualifier: "iter", path: "iter", stdlib: true},
	{qualifier: "time", path: "time", stdlib: true},
	{qualifier: "firestorebind", path: firestorebindImportPath},
	{qualifier: "datastore", path: datastoreImportPath},
}

func writeFirestoreQueryImports(out *bytes.Buffer, body []byte) {
	var stdlib, external []string
	for _, item := range firestoreQueryImports {
		if !usesQualifier(body, item.qualifier) {
			continue
		}
		if item.stdlib {
			stdlib = append(stdlib, item.path)
		} else {
			external = append(external, item.path)
		}
	}
	if len(stdlib)+len(external) == 0 {
		return
	}
	out.WriteString("import (\n")
	for _, path := range stdlib {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	if len(stdlib) > 0 && len(external) > 0 {
		out.WriteString("\n")
	}
	for _, path := range external {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	out.WriteString(")\n\n")
}

type firestoreQueryEmitter struct {
	temps int
	opts  FirestoreQueryOptions
}

func (e *firestoreQueryEmitter) temp(prefix string) string {
	e.temps++
	return fmt.Sprintf("%s%d", prefix, e.temps)
}

func (e *firestoreQueryEmitter) query(b *bytes.Buffer, plan FirestoreQueryPlan) error {
	decl := plan.Decl
	name := decl.Name
	base := lowerFirst(name)

	// The kind is a constant taken from the type rather than from the
	// declaration, so a declaration cannot disagree with the codec about what it
	// is querying. That is why there is no table clause here.
	fmt.Fprintf(b, "// %sKind is the kind %s runs against, which is %s's own.\n", base, name, plan.Entity.Name)
	fmt.Fprintf(b, "const %sKind = %s\n\n", base, strconv.Quote(plan.Entity.Kind))

	if decl.HasIndex {
		// The index is meant to be consumed by a deploy step, so it takes the
		// declaration's own visibility rather than the unexported spelling the
		// kind constant uses. An index a caller cannot reach describes nothing.
		indexName := base + "Index"
		if decl.Exported {
			indexName = name + "Index"
		}
		e.index(b, plan, base, name, indexName)
	}

	result, err := firestoreQueryResult(plan)
	if err != nil {
		return err
	}

	fmt.Fprintf(b, "// %s queries %s.\n", name, plan.Entity.Name)
	if decl.Shape == FirestoreMany {
		b.WriteString("//\n// One range can issue many requests; nothing here reports the boundary.\n")
	}
	if len(plan.Select) > 0 {
		b.WriteString("//\n// This is a projection: only the selected properties are read, and every\n")
		b.WriteString("// other field of the returned value is its zero value. Do not write one back\n")
		b.WriteString("// with Store or Update, which replace the whole entity and would therefore\n")
		b.WriteString("// erase everything this query did not ask for.\n")
		b.WriteString("//\n// A projection reads from an index, so every selected property must be\n")
		b.WriteString("// indexed, and the service rejects projecting a property an equality filter\n")
		b.WriteString("// already fixes.\n")
		if plan.ProjectsAnArray {
			b.WriteString("//\n// One selected property is an array, so the service returns one result per\n")
			b.WriteString("// element rather than one per entity.\n")
		}
	}
	if plan.HasOr {
		b.WriteString("//\n// The filter is disjunctive. Datastore puts the whole filter in disjunctive\n")
		b.WriteString("// normal form and caps the result at datastore.MaxDisjunctions, so an or\n")
		b.WriteString("// nested inside an and multiplies rather than adds. Nothing counts that here:\n")
		b.WriteString("// the expansion rule is the service's, and a count that disagreed would refuse\n")
		b.WriteString("// a query that works.\n")
	}
	if !decl.HasIndex && firestoreNeedsIndexHint(plan) {
		b.WriteString("//\n// This query combines filters and ordering in a shape that may require a\n")
		b.WriteString("// composite index. Nothing in the toolchain verifies that one exists, so a\n")
		b.WriteString("// missing index surfaces as FAILED_PRECONDITION on the first run.\n")
	}
	handle := ""
	if e.opts.ParameterAPI {
		handle = ", h firestorebind.Handle"
	}
	fmt.Fprintf(b, "func %s(ctx context.Context%s%s, opts ...datastore.ReadOption) %s {\n",
		name, handle, firestoreQueryParams(decl), result)

	if err := e.queryValue(b, plan); err != nil {
		return err
	}

	if e.opts.resolves() {
		// The Handle comes from the framework's own Context value, so the
		// resolver's error has to be reported in the shape this declaration
		// returns rather than passed on to a runtime entry that never runs.
		fmt.Fprintf(b, "\th, err := %s.%s(ctx)\n\tif err != nil {\n", resolverAlias, e.opts.HandleResolver.Name)
		switch decl.Shape {
		case FirestoreMany:
			fmt.Fprintf(b, "\t\treturn func(yield func(%s, error) bool) {\n\t\t\tvar zero %s\n\t\t\tyield(zero, err)\n\t\t}\n",
				plan.Entity.Name, plan.Entity.Name)
		case FirestoreBatch:
			fmt.Fprintf(b, "\t\treturn firestorebind.Page[%s]{}, err\n", plan.Entity.Name)
		case FirestoreCount:
			b.WriteString("\t\treturn 0, err\n")
		case FirestoreKeys:
			b.WriteString("\t\treturn firestorebind.KeyPage{}, err\n")
		}
		b.WriteString("\t}\n")
	}
	suffix, arg := "", ""
	if e.opts.ParameterAPI || e.opts.resolves() {
		suffix, arg = "On", "h, "
	}
	switch decl.Shape {
	case FirestoreMany:
		fmt.Fprintf(b, "\treturn firestorebind.Query%s[%s](ctx, %sq, opts...)\n", suffix, plan.Entity.Name, arg)
	case FirestoreBatch:
		fmt.Fprintf(b, "\treturn firestorebind.QueryPage%s[%s](ctx, %sq, opts...)\n", suffix, plan.Entity.Name, arg)
	case FirestoreCount:
		fmt.Fprintf(b, "\treturn firestorebind.Count%s(ctx, %sq, opts...)\n", suffix, arg)
	case FirestoreKeys:
		fmt.Fprintf(b, "\treturn firestorebind.QueryKeysPage%s(ctx, %sq, opts...)\n", suffix, arg)
	}
	b.WriteString("}\n\n")
	return e.transactionForm(b, plan)
}

// transactionForm emits the twin that runs inside a transaction.
//
// It is emitted from the declaration rather than from a discovered call, for the
// reason the key builder is: before it exists there is nothing to discover, so a
// rule that waited for a use would mean it never existed to be used. It is a
// leaf function and the linker drops it when nothing calls it.
//
// The iterator shape gets none. A range inside a transaction issues an unbounded
// number of round trips inside something that has to commit, and a wrapper that
// made that easy would be hiding the cost rather than binding it; a caller who
// wants every entity inside a transaction pages explicitly with the batch form.
func (e *firestoreQueryEmitter) transactionForm(b *bytes.Buffer, plan FirestoreQueryPlan) error {
	decl := plan.Decl
	if decl.Shape == FirestoreMany {
		return nil
	}
	name := decl.Name + "Tx"
	if !decl.Exported {
		name = lowerFirst(decl.Name) + "Tx"
	}
	result, err := firestoreQueryResult(plan)
	if err != nil {
		return err
	}

	fmt.Fprintf(b, "// %s is %s inside a transaction, so its read joins the snapshot the\n", name, decl.Name)
	b.WriteString("// transaction is built on rather than seeing what has been committed since.\n")
	fmt.Fprintf(b, "func %s(ctx context.Context, tx *firestorebind.Tx%s) %s {\n",
		name, firestoreQueryParams(decl), result)
	if err := e.queryValue(b, plan); err != nil {
		return err
	}
	switch decl.Shape {
	case FirestoreBatch:
		fmt.Fprintf(b, "\treturn firestorebind.QueryPageTx[%s](ctx, tx, q)\n", plan.Entity.Name)
	case FirestoreCount:
		b.WriteString("\treturn firestorebind.CountTx(ctx, tx, q)\n")
	case FirestoreKeys:
		b.WriteString("\treturn firestorebind.QueryKeysPageTx(ctx, tx, q)\n")
	}
	b.WriteString("}\n\n")
	return nil
}

// queryValue writes the statements that build the query. Both the plain form and
// the transaction twin call it, so the two cannot drift apart.
func (e *firestoreQueryEmitter) queryValue(b *bytes.Buffer, plan FirestoreQueryPlan) error {
	decl := plan.Decl
	base := lowerFirst(decl.Name)
	fmt.Fprintf(b, "\tq := datastore.NewQuery(%sKind)\n", base)
	if err := e.filters(b, plan); err != nil {
		return fmt.Errorf("firestorebind: statement %s: %w", decl.Name, err)
	}
	if plan.Ancestor != "" {
		fmt.Fprintf(b, "\tq = q.Ancestor(%s)\n", plan.Ancestor)
	}
	for _, order := range plan.Orders {
		entry := "Order"
		if order.Order.Direction == FirestoreDescending {
			entry = "OrderDesc"
		}
		fmt.Fprintf(b, "\tq = q.%s(%s)\n", entry, strconv.Quote(order.Field.Property))
	}
	if bound, ok := firestoreBoundExpr(decl.Limit); ok {
		fmt.Fprintf(b, "\tq = q.Limit(%s)\n", bound)
	}
	if bound, ok := firestoreBoundExpr(decl.Offset); ok {
		fmt.Fprintf(b, "\tq = q.Offset(%s)\n", bound)
	}
	if len(plan.Select) > 0 {
		fmt.Fprintf(b, "\tq = q.Project(%s)\n", quotedList(plan.Select))
	}
	if len(plan.Distinct) > 0 {
		fmt.Fprintf(b, "\tq = q.DistinctOn(%s)\n", quotedList(plan.Distinct))
	}
	if plan.Start != "" {
		fmt.Fprintf(b, "\tq = q.Start(%s)\n", plan.Start)
	}
	if plan.End != "" {
		fmt.Fprintf(b, "\tq = q.End(%s)\n", plan.End)
	}
	if decl.Shape == FirestoreKeys {
		b.WriteString("\tq = q.KeysOnly()\n")
	}
	return nil
}

func quotedList(names []string) string {
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = strconv.Quote(name)
	}
	return strings.Join(quoted, ", ")
}

// index emits the composite index the author declared, as a value a deploy step
// can marshal. Nothing derives it; see decision:firestore-no-schema-artifact.
func (e *firestoreQueryEmitter) index(b *bytes.Buffer, plan FirestoreQueryPlan, base, name, indexName string) {
	fmt.Fprintf(b, "// %s is the composite index %s declares it needs.\n", indexName, name)
	b.WriteString("//\n// It is a description, not a request: applying an index is an admin-API\n")
	b.WriteString("// operation. Feed it to datastore.MarshalIndexYAML and to whatever owns\n")
	b.WriteString("// index.yaml in this project.\n")
	fmt.Fprintf(b, "var %s = datastore.Index{\n", indexName)
	fmt.Fprintf(b, "\tKind: %sKind,\n", base)
	if plan.Ancestor != "" {
		b.WriteString("\tAncestor: true,\n")
	}
	b.WriteString("\tProperties: []datastore.IndexProperty{\n")
	for _, property := range plan.Decl.Index {
		direction := "datastore.Ascending"
		if property.Direction == FirestoreDescending {
			direction = "datastore.Descending"
		}
		fmt.Fprintf(b, "\t\t{Name: %s, Direction: %s},\n", strconv.Quote(property.Name), direction)
	}
	b.WriteString("\t},\n}\n\n")
}

// filters emits the where clause.
//
// A declaration with no or keeps the per-predicate Filter calls this has always
// written: Query.Filter is sugar over Where(Prop(...)) upstream, so the flat
// form costs nothing and reads as it did. Only a tree that actually needs OR
// becomes one.
func (e *firestoreQueryEmitter) filters(b *bytes.Buffer, plan FirestoreQueryPlan) error {
	if plan.Where == nil {
		return nil
	}
	if !plan.HasOr {
		for _, filter := range plan.Filters {
			if err := e.filter(b, filter); err != nil {
				return err
			}
		}
		return nil
	}

	// A multi-valued comparison builds its candidates as statements, so those
	// come out before the expression that refers to them.
	names := make([]string, len(plan.Filters))
	for i, filter := range plan.Filters {
		if !filter.Predicate.Op.Multi() {
			continue
		}
		name, err := e.members(b, filter)
		if err != nil {
			return err
		}
		names[i] = name
	}

	at := 0
	expr, err := e.condition(*plan.Where, plan.Filters, names, &at)
	if err != nil {
		return err
	}
	fmt.Fprintf(b, "\tq = q.Where(%s)\n", expr)
	return nil
}

// condition renders one node of the tree. Leaves are consumed in walk order,
// which is the order the checker recorded them in, so the expression and the
// hoisted statements cannot disagree about which parameter belongs where.
func (e *firestoreQueryEmitter) condition(c FirestoreCondition, filters []FirestoreQueryFilter, names []string, at *int) (string, error) {
	if c.IsLeaf() {
		i := *at
		*at++
		if i >= len(filters) {
			return "", fmt.Errorf("the condition tree has more comparisons than the checker recorded")
		}
		return e.propExpr(filters[i], names[i])
	}
	parts := make([]string, len(c.Operands))
	for i, operand := range c.Operands {
		part, err := e.condition(operand, filters, names, at)
		if err != nil {
			return "", err
		}
		parts[i] = part
	}
	entry := "datastore.And"
	if c.Junction == FirestoreOr {
		entry = "datastore.Or"
	}
	// One operand per line. A nested tree on one line is the kind of generated
	// code that has to be re-read to be understood, and gofmt indents what is
	// already broken rather than joining it back up.
	return entry + "(\n" + strings.Join(parts, ",\n") + ",\n)", nil
}

// propExpr is one comparison as a datastore.Prop call.
func (e *firestoreQueryEmitter) propExpr(filter FirestoreQueryFilter, members string) (string, error) {
	property := strconv.Quote(filter.Field.Property)
	op := firestoreOpConstant(filter.Predicate.Op)
	if filter.Predicate.Op.Multi() {
		return fmt.Sprintf("datastore.Prop(%s, %s, datastore.Array(%s...))", property, op, members), nil
	}
	expr, ok := firestoreScalarEncode(filter.Param.Name, filter.Field.Type)
	if !ok {
		return "", fmt.Errorf("property %s cannot be a filter value", filter.Field.Property)
	}
	return fmt.Sprintf("datastore.Prop(%s, %s, %s)", property, op, expr), nil
}

// members builds the candidate slice an in or not-in comparison needs, and
// returns the variable holding it.
func (e *firestoreQueryEmitter) members(b *bytes.Buffer, filter FirestoreQueryFilter) (string, error) {
	name := e.temp("members")
	element := e.temp("member")
	fmt.Fprintf(b, "\t%s := make([]datastore.Value, 0, len(%s))\n", name, filter.Param.Name)
	fmt.Fprintf(b, "\tfor _, %s := range %s {\n", element, filter.Param.Name)
	expr, ok := firestoreScalarEncode(element, filter.Field.Type)
	if !ok {
		return "", fmt.Errorf("property %s cannot be a filter value", filter.Field.Property)
	}
	fmt.Fprintf(b, "\t\t%s = append(%s, %s)\n", name, name, expr)
	b.WriteString("\t}\n")
	return name, nil
}

// filter emits one property filter. The value goes through the same encoders the
// codec uses, so a filter and a stored property cannot disagree about how a
// value is written.
func (e *firestoreQueryEmitter) filter(b *bytes.Buffer, filter FirestoreQueryFilter) error {
	property := strconv.Quote(filter.Field.Property)
	op := firestoreOpConstant(filter.Predicate.Op)

	if filter.Predicate.Op.Multi() {
		members, err := e.members(b, filter)
		if err != nil {
			return err
		}
		fmt.Fprintf(b, "\tq = q.Filter(%s, %s, datastore.Array(%s...))\n", property, op, members)
		return nil
	}

	expr, ok := firestoreScalarEncode(filter.Param.Name, filter.Field.Type)
	if !ok {
		return fmt.Errorf("property %s cannot be a filter value", filter.Field.Property)
	}
	fmt.Fprintf(b, "\tq = q.Filter(%s, %s, %s)\n", property, op, expr)
	return nil
}

func firestoreOpConstant(op FirestoreOp) string {
	switch op {
	case FirestoreEqual:
		return "datastore.Equal"
	case FirestoreNotEqual:
		return "datastore.NotEqual"
	case FirestoreLess:
		return "datastore.LessThan"
	case FirestoreLessOrEqual:
		return "datastore.LessThanOrEqual"
	case FirestoreGreater:
		return "datastore.GreaterThan"
	case FirestoreGreaterOrEqual:
		return "datastore.GreaterThanEqual"
	case FirestoreIn:
		return "datastore.In"
	case FirestoreNotIn:
		return "datastore.NotIn"
	default:
		return "datastore.Equal"
	}
}

// firestoreBoundExpr writes a limit or offset as the int32 the driver takes.
func firestoreBoundExpr(bound FirestoreBound) (string, bool) {
	if !bound.Present {
		return "", false
	}
	if bound.Param != "" {
		return "int32(" + bound.Param + ")", true
	}
	return strconv.Itoa(bound.Literal), true
}

// firestoreQueryResult is the Go result type a declaration's shape selects.
func firestoreQueryResult(plan FirestoreQueryPlan) (string, error) {
	switch plan.Decl.Shape {
	case FirestoreBatch:
		return fmt.Sprintf("(firestorebind.Page[%s], error)", plan.Entity.Name), nil
	case FirestoreMany:
		return fmt.Sprintf("iter.Seq2[%s, error]", plan.Entity.Name), nil
	case FirestoreCount:
		return "(int64, error)", nil
	case FirestoreKeys:
		return "(firestorebind.KeyPage, error)", nil
	default:
		return "", fmt.Errorf("firestorebind: statement %s has no result shape", plan.Decl.Name)
	}
}

// firestoreQueryParams writes the declared parameters as a Go parameter list.
func firestoreQueryParams(decl FirestoreQueryDecl) string {
	if len(decl.Params) == 0 {
		return ""
	}
	typed := make([]string, 0, len(decl.Params))
	for _, param := range decl.Params {
		typed = append(typed, param.Name+" "+param.Type)
	}
	return ", " + strings.Join(typed, ", ")
}

// firestoreNeedsIndexHint reports the shapes that commonly require a composite
// index, for the godoc warning only.
//
// It is deliberately not a derivation: the real rule is subtle, and a generated
// diagnostic that named the wrong index would read as authoritative while
// leaving the query broken. This only says "may", and only where more than one
// property is involved.
func firestoreNeedsIndexHint(plan FirestoreQueryPlan) bool {
	if plan.Decl.Shape == FirestoreCount {
		// A count runs the aggregation query, and warning about ordering it
		// would be noise: the parser already rejects an order clause there.
		return false
	}
	properties := map[string]bool{}
	inequality := false
	for _, filter := range plan.Filters {
		properties[filter.Field.Property] = true
		if filter.Predicate.Op != FirestoreEqual {
			inequality = true
		}
	}
	for _, order := range plan.Orders {
		properties[order.Field.Property] = true
	}
	switch {
	case plan.HasOr:
		// Each disjunct is indexed on its own terms, so an OR over more than one
		// property is at least as likely to need a composite as the AND shapes
		// below.
		return true
	case len(plan.Select) > 0 || len(plan.Distinct) > 0:
		// A projection always reads from an index, and one over more than the
		// automatic single-property indexes needs a composite.
		return true
	case len(plan.Orders) > 1:
		return true
	case plan.Ancestor != "" && (len(plan.Orders) > 0 || len(plan.Filters) > 0):
		// An ancestor query that also sorts or filters needs an ancestor index,
		// which is a composite index by another name.
		return true
	default:
		return len(properties) > 1 && (inequality || len(plan.Orders) > 0)
	}
}
