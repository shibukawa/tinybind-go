// The two profiles are different contracts, and the generated code pins which
// one it reads. A wire codec handed a map is the two ends running different
// protocols, which is exactly what pinning exists to catch.
func TestAWireCodecRefusesAWorldMessage(t *testing.T) {
	dir := cborFixture(t, map[string]string{
		"fixed.go": fixedPointSource,
		"input.go": playerInputSource,
	})
	writeCborCodec(t, dir)
	writeProbe(t, dir, `
func TestAMapIsNotAWireMessage(t *testing.T) {
	// The same four values, written the way a world-profile encoder would.
	world := cbor.AppendMapHeader(nil, 4)
	world = cbor.AppendText(world, "Tick")
	world = cbor.AppendUint(world, 1234)
	world = cbor.AppendText(world, "MoveX")
	world = cbor.AppendInt(world, -1)
	world = cbor.AppendText(world, "MoveY")
	world = cbor.AppendInt(world, 0)
	world = cbor.AppendText(world, "Buttons")
	world = cbor.AppendUint(world, 3)

	var out PlayerInput
	if err := out.DecodeCBORFrom(world); err == nil {
		t.Fatal("a wire codec read a world-profile message")
	}
	// And the wire profile refuses those bytes outright, before any decoding.
	if err := cbor.Wire().Validate(world); err == nil {
		t.Fatal("the wire profile accepted a map")
	}
}
`)
	runProbe(t, dir)
}

