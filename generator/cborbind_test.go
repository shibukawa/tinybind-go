// The mapping pass walks every package-level struct, including ones no mapping
// path will ever touch. Refusing the whole run for a field kind that would
// never have been emitted made those packages ungeneratable for a reason that
// never applied to them -- and made this mode unreachable from the combined
// CLI, since a sized integer per field is exactly what the wire profile is for.
func TestAStructNoMappingPathTouchesDoesNotFailTheRun(t *testing.T) {
	dir := t.TempDir()
	writeTempModule(t, dir)
	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(`package main

import "github.com/shibukawa/tinybind-go/cborbind"

// PlayerInput is a CBOR message. Nothing binds it, writes it, or asks for a
// JSON codec, and its sized integers are what fieldTypeKind cannot map.
type PlayerInput struct {
	Tick    uint32
	Buttons uint16
}

var _ = cborbind.GenerateWireCodec[PlayerInput]()

func main() {}
`), 0o644); err != nil {
		t.Fatal(err)
	}
	tidyTempModule(t, dir)

	// DefaultOptions, which is what the generate command runs with.
	// AnalyzePackage sets GenerateAll, and asking for everything still means
	// asking for this one.
	if _, err := generator.AnalyzePackageWithOptions(dir, generator.DefaultOptions()); err != nil {
		t.Fatalf("a struct nothing maps failed the mapping analysis: %v", err)
	}
	plan, err := generator.AnalyzeCborCodecsWithOptions(dir, generator.DefaultOptions())
	if err != nil {
		t.Fatalf("analyze cbor: %v", err)
	}
	if len(plan.Types) != 1 {
		t.Fatalf("planned %d CBOR types, want 1", len(plan.Types))
	}
}

