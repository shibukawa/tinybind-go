// The wire profile has no field names, so a struct that reaches it as a nested
// field composes into the same array rather than growing one of its own.
func TestNestedStructAppendsIntoTheSameBuffer(t *testing.T) {
	code := generateCbor(t, `package main

import "github.com/shibukawa/tinybind-go/cborbind"

type Vec2 struct {
	X int32
	Y int32
}

type Move struct {
	Tick uint32
	At   Vec2
}

var _ = cborbind.GenerateWireCodec[Move]()
`)
	for _, want := range []string{
		"func appendMoveCBORWire(dst []byte, v Move) []byte",
		"dst = appendVec2CBORWire(dst, v.At)",
		"func appendVec2CBORWire(dst []byte, v Vec2) []byte",
		"if err := decodeVec2CBORWire(r, &v.At); err != nil",
	} {
		if !strings.Contains(code, want) {
			t.Fatalf("generated code does not contain %q\n%s", want, code)
		}
	}
	// A nested type nothing declared gets the functions and no public method:
	// a method is code size in every binary carrying the type, and nothing
	// asked for one.
	if strings.Contains(code, "func (v Vec2) AppendCBORTo") {
		t.Fatalf("a nested type acquired a public method it never asked for\n%s", code)
	}
	if !strings.Contains(code, "func (v Move) AppendCBORTo") {
		t.Fatalf("the declared type did not publish its method\n%s", code)
	}
}

