package generator_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/shibukawa/tinybind-go/generator"
)

// brandedRegistry is what a framework generating routes with this module writes
// when it brands its own output: an ordinary generated registry, headed by a
// line naming the framework rather than tinybind.
const brandedRegistry = `// Code generated by Popcorn Wave via TinyBind; DO NOT EDIT.

package sample

import "net/http"

func Register(mux *http.ServeMux) {
	mux.HandleFunc("GET /about", func(w http.ResponseWriter, r *http.Request) {})
}
`

func writeBrandedPackage(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	writeTempModule(t, dir)
	if err := os.WriteFile(filepath.Join(dir, "routes_gen.go"), []byte(brandedRegistry), 0o644); err != nil {
		t.Fatal(err)
	}
	tidyTempModule(t, dir)
	return dir
}

// TestBrandedGeneratedRegistryIsDiscoveredWithoutRegistration records the
// default: a header this module does not recognize is read like hand-written
// code, so the pages a framework's registry installs become documented routes.
func TestBrandedGeneratedRegistryIsDiscoveredWithoutRegistration(t *testing.T) {
	doc, err := generator.New(generator.DefaultOptions()).BuildOpenAPI(writeBrandedPackage(t))
	if err != nil {
		t.Fatalf("BuildOpenAPI: %v", err)
	}
	paths, _ := doc["paths"].(map[string]any)
	if _, found := paths["/about"]; !found {
		t.Fatalf("expected the unregistered header to be discovered, got %v", paths)
	}
}

// TestRegisteredGeneratedHeaderIsSkipped is the fix: naming the prefix keeps a
// framework's own generated registry out of every discovery pass, exactly as
// this module's own header already is.
func TestRegisteredGeneratedHeaderIsSkipped(t *testing.T) {
	options := generator.DefaultOptions()
	options.GeneratedHeaders = []string{"Code generated by Popcorn Wave"}

	doc, err := generator.New(options).BuildOpenAPI(writeBrandedPackage(t))
	if err != nil {
		t.Fatalf("BuildOpenAPI: %v", err)
	}
	paths, _ := doc["paths"].(map[string]any)
	if len(paths) != 0 {
		t.Errorf("a generated page registration entered the document: %v", paths)
	}
}

// TestRegisteredHeaderStillRequiresTheConventionalEnding keeps the registration
// from turning into a match on any leading comment.
func TestRegisteredHeaderStillRequiresTheConventionalEnding(t *testing.T) {
	dir := t.TempDir()
	writeTempModule(t, dir)
	source := strings.Replace(brandedRegistry, "; DO NOT EDIT.", ".", 1)
	if err := os.WriteFile(filepath.Join(dir, "routes_gen.go"), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	tidyTempModule(t, dir)

	options := generator.DefaultOptions()
	options.GeneratedHeaders = []string{"Code generated by Popcorn Wave"}
	doc, err := generator.New(options).BuildOpenAPI(dir)
	if err != nil {
		t.Fatalf("BuildOpenAPI: %v", err)
	}
	paths, _ := doc["paths"].(map[string]any)
	if _, found := paths["/about"]; !found {
		t.Errorf("a comment without the generated-file ending was treated as generated: %v", paths)
	}
}
