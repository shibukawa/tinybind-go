package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// DynamoQueryOptions selects which generated surfaces a package publishes. The
// explicit client-taking function is always one of them; the Context-resolved
// wrapper is opt-in, as decision:dynamo-context-client-api describes.
type DynamoQueryOptions struct {
	// ContextAPI adds a "<Name>Context" wrapper resolving the client and the
	// deployment table name from the Context.
	ContextAPI bool
	// ContextOnly publishes only the Context-resolved surface, under the
	// declared name. The client-taking function becomes unexported and no
	// "<Name>Context" is generated, so that name stays free. It implies
	// ContextAPI.
	ContextOnly bool
	// Resolver selects a framework resolver of the shape
	// func(context.Context, string) (*dynamodb.Client, string, error), taking
	// the declared table name and returning the client and the deployment name.
	// Nil uses dynamobind.TableFromContext. Setting it implies ContextAPI.
	Resolver *SymbolPattern
}

func (o DynamoQueryOptions) contextAPI() bool {
	return o.ContextAPI || o.ContextOnly || o.Resolver != nil
}

// dynamoResolverAlias is the import alias a framework resolver is called
// through, so the resolver's own package name cannot collide with anything the
// generated file already imports.
const dynamoResolverAlias = "_tinybindresolver"

// EmitDynamoQueries generates one function per checked declaration.
func EmitDynamoQueries(pkg string, plans []DynamoQueryPlan, options DynamoQueryOptions) ([]byte, error) {
	if len(plans) == 0 {
		return nil, nil
	}
	if err := checkDynamoQueryNames(plans, options); err != nil {
		return nil, err
	}
	var body bytes.Buffer
	for _, plan := range plans {
		if err := emitDynamoQuery(&body, plan, options); err != nil {
			return nil, err
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tinybind; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", pkg)
	writeDynamoQueryImports(&out, body.Bytes(), options)
	out.Write(body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("dynamobind: format generated query: %w\n%s", err, out.String())
	}
	return formatted, nil
}

// checkDynamoQueryNames rejects a set of declarations whose generated names
// would collide. Only the Context mode can produce one, by appending Context to
// a name another declaration already carries.
func checkDynamoQueryNames(plans []DynamoQueryPlan, options DynamoQueryOptions) error {
	if !options.contextAPI() || options.ContextOnly {
		return nil
	}
	declared := make(map[string]bool, len(plans))
	for _, plan := range plans {
		declared[plan.Decl.Name] = true
	}
	for _, plan := range plans {
		if declared[plan.Decl.Name+"Context"] {
			return fmt.Errorf("%s:%d: statement %s: its generated Context wrapper is named %sContext, which is already a declared statement",
				plan.Decl.SourcePath, plan.Decl.Line, plan.Decl.Name, plan.Decl.Name)
		}
	}
	return nil
}

var dynamoQueryImports = []struct {
	qualifier string
	path      string
	stdlib    bool
}{
	{qualifier: "context", path: "context", stdlib: true},
	{qualifier: "iter", path: "iter", stdlib: true},
	{qualifier: "time", path: "time", stdlib: true},
	{qualifier: "dynamobind", path: dynamobindImportPath},
	{qualifier: "dynamodb", path: dynamodbImportPath},
}

func writeDynamoQueryImports(out *bytes.Buffer, body []byte, options DynamoQueryOptions) {
	var stdlib, external []string
	for _, item := range dynamoQueryImports {
		if !usesQualifier(body, item.qualifier) {
			continue
		}
		if item.stdlib {
			stdlib = append(stdlib, item.path)
		} else {
			external = append(external, item.path)
		}
	}
	resolver := ""
	if options.Resolver != nil && usesQualifier(body, dynamoResolverAlias) {
		resolver = fmt.Sprintf("\t%s %q\n", dynamoResolverAlias, options.Resolver.PackagePath)
	}
	if len(stdlib)+len(external) == 0 && resolver == "" {
		return
	}
	out.WriteString("import (\n")
	for _, path := range stdlib {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	if len(stdlib) > 0 && (len(external) > 0 || resolver != "") {
		out.WriteString("\n")
	}
	for _, path := range external {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	out.WriteString(resolver)
	out.WriteString(")\n\n")
}

// dynamoExplicitName names the function taking an explicit client. Context-only
// mode makes it unexported so the declared name can carry the Context-resolved
// API instead.
func dynamoExplicitName(name string, options DynamoQueryOptions) string {
	if options.ContextOnly {
		return "_tinybindDynamo" + name
	}
	return name
}

// dynamoContextName names the Context-resolved function.
func dynamoContextName(name string, options DynamoQueryOptions) string {
	if options.ContextOnly {
		return name
	}
	return name + "Context"
}

// dynamoResolverCall is the expression resolving the client and the deployment
// table name from a Context.
func dynamoResolverCall(options DynamoQueryOptions, table string) string {
	if options.Resolver != nil {
		return fmt.Sprintf("%s.%s(ctx, %s)", dynamoResolverAlias, options.Resolver.Name, table)
	}
	return fmt.Sprintf("dynamobind.TableFromContext(ctx, %s)", table)
}

func emitDynamoQuery(b *bytes.Buffer, plan DynamoQueryPlan, options DynamoQueryOptions) error {
	decl := plan.Decl
	name := decl.Name
	base := lowerFirst(name)

	// The table, the expression and its aliases are constants: every name is
	// known here, so nothing is assembled at run time. Every attribute is
	// aliased whether or not it is a reserved word, which is why no reserved-word
	// list has to be carried.
	fmt.Fprintf(b, "// %sTable is the table %s declares.\n", base, name)
	fmt.Fprintf(b, "const %sTable = %s\n\n", base, strconv.Quote(decl.Table))

	fmt.Fprintf(b, "// %sKeyCondition is the key condition of %s.\n", base, name)
	fmt.Fprintf(b, "const %sKeyCondition = %s\n\n", base, strconv.Quote(plan.Expression))

	fmt.Fprintf(b, "var %sAttributeNames = map[string]string{\n", base)
	aliases := make([]string, 0, len(plan.Names))
	for alias := range plan.Names {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	for _, alias := range aliases {
		fmt.Fprintf(b, "\t%s: %s,\n", strconv.Quote(alias), strconv.Quote(plan.Names[alias]))
	}
	b.WriteString("}\n\n")

	if err := emitDynamoQueryCore(b, plan, base); err != nil {
		return err
	}
	emitDynamoQueryExplicit(b, plan, base, options)
	if options.contextAPI() {
		emitDynamoQueryContext(b, plan, base, options)
	}
	return nil
}

// dynamoQueryResult is the Go result type a declaration's shape selects.
func dynamoQueryResult(plan DynamoQueryPlan) (string, error) {
	switch plan.Decl.Shape {
	case DynamoPage:
		return fmt.Sprintf("(dynamobind.Page[%s], error)", plan.Item.Name), nil
	case DynamoMany:
		return fmt.Sprintf("iter.Seq2[%s, error]", plan.Item.Name), nil
	default:
		return "", fmt.Errorf("dynamobind: statement %s has no result shape", plan.Decl.Name)
	}
}

// dynamoQueryParams writes the declared parameters as a Go parameter list, and
// as the argument list that forwards them.
func dynamoQueryParams(decl DynamoQueryDecl) (declaration, arguments string) {
	names := make([]string, 0, len(decl.Params))
	typed := make([]string, 0, len(decl.Params))
	for _, param := range decl.Params {
		names = append(names, param.Name)
		typed = append(typed, param.Name+" "+param.Type)
	}
	if len(names) == 0 {
		return "", ""
	}
	return ", " + strings.Join(typed, ", "), ", " + strings.Join(names, ", ")
}

// emitDynamoQueryCore writes the unexported function holding the condition.
// Both published surfaces delegate to it, differing only in where the table
// name comes from, so a deployment prefix costs no second copy of the body.
func emitDynamoQueryCore(b *bytes.Buffer, plan DynamoQueryPlan, base string) error {
	decl := plan.Decl
	result, err := dynamoQueryResult(plan)
	if err != nil {
		return err
	}
	params, _ := dynamoQueryParams(decl)

	fmt.Fprintf(b, "func %sQuery(ctx context.Context, c *dynamodb.Client, table string%s, opts ...dynamodb.QueryOption) %s {\n",
		base, params, result)
	b.WriteString("\tvalues := map[string]dynamodb.AttributeValue{\n")
	for _, value := range plan.Values {
		expr, ok := dynamoScalarEncode(value.Param.Name, value.Attribute.Type)
		if !ok {
			return fmt.Errorf("dynamobind: statement %s: attribute %s cannot be a key value", decl.Name, value.Attribute.Attribute)
		}
		fmt.Fprintf(b, "\t\t%s: %s,\n", strconv.Quote(value.Placeholder), expr)
	}
	b.WriteString("\t}\n")

	// The generated options go last so a caller option never replaces the names
	// or values this condition depends on.
	b.WriteString("\topts = append(opts,\n")
	fmt.Fprintf(b, "\t\tdynamodb.WithExpressionNames(%sAttributeNames),\n", base)
	b.WriteString("\t\tdynamodb.WithExpressionValues(values),\n\t)\n")

	entry := "Query"
	if decl.Shape == DynamoPage {
		entry = "QueryPage"
	}
	fmt.Fprintf(b, "\treturn dynamobind.%s[%s](ctx, c, table, %sKeyCondition, opts...)\n}\n\n",
		entry, plan.Item.Name, base)
	return nil
}

func emitDynamoQueryExplicit(b *bytes.Buffer, plan DynamoQueryPlan, base string, options DynamoQueryOptions) {
	decl := plan.Decl
	name := dynamoExplicitName(decl.Name, options)
	result, _ := dynamoQueryResult(plan)
	params, arguments := dynamoQueryParams(decl)

	fmt.Fprintf(b, "// %s queries %s in %s.\n", name, plan.Item.Name, decl.Table)
	fmt.Fprintf(b, "func %s(ctx context.Context, c *dynamodb.Client%s, opts ...dynamodb.QueryOption) %s {\n",
		name, params, result)
	fmt.Fprintf(b, "\treturn %sQuery(ctx, c, %sTable%s, opts...)\n}\n\n", base, base, arguments)
}

func emitDynamoQueryContext(b *bytes.Buffer, plan DynamoQueryPlan, base string, options DynamoQueryOptions) {
	decl := plan.Decl
	name := dynamoContextName(decl.Name, options)
	result, _ := dynamoQueryResult(plan)
	params, arguments := dynamoQueryParams(decl)
	resolve := dynamoResolverCall(options, base+"Table")

	fmt.Fprintf(b, "// %s queries %s, resolving the client and the deployment name of %s from ctx.\n",
		name, plan.Item.Name, decl.Table)
	fmt.Fprintf(b, "func %s(ctx context.Context%s, opts ...dynamodb.QueryOption) %s {\n", name, params, result)

	if decl.Shape == DynamoPage {
		fmt.Fprintf(b, "\tc, table, err := %s\n", resolve)
		fmt.Fprintf(b, "\tif err != nil {\n\t\treturn dynamobind.Page[%s]{}, err\n\t}\n", plan.Item.Name)
		fmt.Fprintf(b, "\treturn %sQuery(ctx, c, table%s, opts...)\n}\n\n", base, arguments)
		return
	}
	// The iterator form cannot return the resolver error, so it yields it once
	// and stops, which is how a failed page already reports.
	fmt.Fprintf(b, "\tc, table, err := %s\n", resolve)
	fmt.Fprintf(b, "\tif err != nil {\n")
	fmt.Fprintf(b, "\t\treturn func(yield func(%s, error) bool) { yield(%s{}, err) }\n\t}\n",
		plan.Item.Name, plan.Item.Name)
	fmt.Fprintf(b, "\treturn %sQuery(ctx, c, table%s, opts...)\n}\n\n", base, arguments)
}
