package generator

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// EmitCborCodecs generates the CBOR codec for every plan in the package.
func EmitCborCodecs(plan *CborPackagePlan) ([]byte, error) {
	if plan == nil {
		return nil, fmt.Errorf("cborbind: nil plan")
	}
	e := &cborEmitter{plan: plan, index: map[string]CborTypePlan{}, helpers: map[string]string{}}
	for _, item := range plan.Types {
		e.index[item.Name] = item
	}
	for _, item := range plan.Types {
		e.item(item)
	}
	for _, item := range plan.Types {
		if item.Delta {
			e.emitDelta(item)
		}
	}
	if e.body.Len() == 0 {
		return nil, nil
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tinybind; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", plan.Package)
	fmt.Fprintf(&out, "import %q\n\n", cborImportPath)
	e.writeProfiles(&out)
	e.writeVersion(&out)
	e.writeWholeCollections(&out)
	out.Write(e.body.Bytes())
	e.writeHelpers(&out)

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return out.Bytes(), fmt.Errorf("cborbind: format generated code: %w\n%s", err, out.String())
	}
	return formatted, nil
}

type cborEmitter struct {
	plan *CborPackagePlan
	body bytes.Buffer
	// index resolves a nested type's plan by name, for the delta walk.
	index map[string]CborTypePlan
	// helpers holds the delta types and functions the walk needs, keyed by name
	// so a shape met twice is written once. They are emitted in sorted order, so
	// the file does not depend on the order the walk met them in.
	helpers map[string]string
	// wire and world record which profile vars are actually referenced. Only a
	// published decoder reads one, so an encode-only package declares neither
	// rather than carrying a var nothing names.
	wire  bool
	world bool
}

// writeProfiles declares the profile a codec reads under, and beside it the
// read limits that used to be bundled into the driver's named profiles.
//
// Since tinygodriver v1.2.7 a Profile is a format restriction the consumer
// spells out as a struct literal, and every resource limit is a
// DecoderOptions passed alongside. The literal is a package-level var rather
// than a call at each entry, because a codec runs once per message per player
// per tick and the profile never changes; and it is named in the generated
// decoder rather than taken from the caller, because pinning it is what stops
// a wire codec reading a world message. The limits keep the ceilings the old
// bundled profiles enforced, so the bump changes no observable behavior; the
// nesting bound is left to the driver's stack safety net, which is the half
// the old bundling got wrong.
func (e *cborEmitter) writeProfiles(out *bytes.Buffer) {
	if e.wire {
		out.WriteString("// cborWireProfile is the format restriction the wire codecs below were\n" +
			"// generated for. It is pinned here rather than taken from the caller: the two\n" +
			"// ends of a connection must not disagree about which profile is in use.\n" +
			"var cborWireProfile = cbor.Profile{\n" +
			"\tName:             \"wire\",\n" +
			"\tRejectMaps:       true,\n" +
			"\tRejectTags:       true,\n" +
			"\tRejectFloats:     true,\n" +
			"\tRejectIndefinite: true,\n" +
			"\tRejectTextKeys:   true,\n" +
			"}\n\n" +
			"// cborWireReadOptions carries the read limits for wire messages: a fixed-shape\n" +
			"// realtime message is small, and a larger one is an attack rather than data.\n" +
			"var cborWireReadOptions = cbor.DecoderOptions{\n" +
			"\tMaxInputBytes:      64 << 10,\n" +
			"\tMaxContainerItems:  1024,\n" +
			"\tMaxStringBytes:     4096,\n" +
			"\tMaxRawMessageBytes: 8 << 10,\n" +
			"}\n\n")
	}
	if e.world {
		out.WriteString("// cborWorldProfile is the format restriction the world codecs below were\n" +
			"// generated for.\n" +
			"var cborWorldProfile = cbor.Profile{\n" +
			"\tName:              \"world\",\n" +
			"\tRequireSortedKeys: true,\n" +
			"\tKeyOrder:          cbor.BytewiseKeyOrder,\n" +
			"\tRejectFloats:      true,\n" +
			"\tRejectIndefinite:  true,\n" +
			"}\n\n" +
			"// cborWorldReadOptions carries the read limits for world snapshots, which are\n" +
			"// rare and large where a wire message is constant and small.\n" +
			"var cborWorldReadOptions = cbor.DecoderOptions{\n" +
			"\tMaxInputBytes:      64 << 20,\n" +
			"\tMaxContainerItems:  65536,\n" +
			"\tMaxStringBytes:     4 << 20,\n" +
			"\tMaxRawMessageBytes: 64 << 20,\n" +
			"}\n\n")
	}
}

// writeVersion emits the protocol version and the schema it was derived from.
//
// Both are emitted, not only the digest: a version mismatch between a client
// and a server is then diagnosed by diffing two schemas rather than by
// observing that two opaque numbers differ.
func (e *cborEmitter) writeVersion(out *bytes.Buffer) {
	out.WriteString("// CBORProtocolVersion identifies the wire shape of every codec in this file.\n" +
		"// It is derived from CBORSchema and covers wire-observable shape alone, so\n" +
		"// regenerating with a newer tinybind that emits the same bytes leaves it\n" +
		"// unchanged, and any change that moves one byte moves it.\n")
	fmt.Fprintf(out, "const CBORProtocolVersion = %q\n\n", e.plan.Version)
	out.WriteString("// CBORSchema is the canonical description CBORProtocolVersion digests.\n")
	fmt.Fprintf(out, "const CBORSchema = %s\n\n", cborRawString(e.plan.Schema))
}

// cborRawString writes a multi-line constant as a raw string where it can be,
// falling back to a quoted one for a schema holding a backquote.
func cborRawString(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return fmt.Sprintf("%q", s)
}

func (e *cborEmitter) item(item CborTypePlan) {
	if item.Usage == 0 {
		return
	}
	if item.Usage&CborEncode != 0 {
		e.appendFunc(item)
	}
	if item.Usage&CborDecode != 0 {
		e.decodeFunc(item)
	}
	if !item.Declared {
		return
	}
	if item.Usage&CborEncode != 0 {
		e.appendMethod(item)
	}
	if item.Usage&CborDecode != 0 {
		e.decodeMethod(item)
	}
}

// cborFuncSuffix distinguishes the two profiles' functions for one type. A
// struct reached from a wire root and from a world root needs both, because the
// profiles disagree about the container it encodes as.
func cborFuncSuffix(profile CborProfile) string {
	if profile == CborWorld {
		return "World"
	}
	return "Wire"
}

func cborAppendFuncName(item CborTypePlan) string {
	return "append" + item.Name + "CBOR" + cborFuncSuffix(item.Profile)
}

func cborDecodeFuncName(item CborTypePlan) string {
	return "decode" + item.Name + "CBOR" + cborFuncSuffix(item.Profile)
}

// appendFunc emits the encoder.
//
// It appends into the destination the caller already holds, at every depth, so
// a nested struct costs no intermediate buffer and no allocation. That is the
// whole reason the driver's contract takes a destination rather than returning
// bytes.
func (e *cborEmitter) appendFunc(item CborTypePlan) {
	b := &e.body
	fmt.Fprintf(b, "// %s appends v as one %s-profile CBOR item.\n", cborAppendFuncName(item), item.Profile)
	if item.Profile == CborWire {
		fmt.Fprintf(b, "//\n// The array is %d long and its order is the declaration order of %s.\n"+
			"// Both are part of the protocol: a reader counts on the position.\n", len(item.Fields), item.Name)
	} else {
		b.WriteString("//\n// Keys are written in the bytewise order of their encoded form, which is the\n" +
			"// core deterministic encoding of RFC 8949 and the order the world profile\n" +
			"// enforces. The order is fixed here, so two runs write the same bytes.\n")
	}
	fmt.Fprintf(b, "func %s(dst []byte, v %s) []byte {\n", cborAppendFuncName(item), item.Name)
	if item.Profile == CborWire {
		fmt.Fprintf(b, "\tdst = cbor.AppendArrayHeader(dst, %d)\n", len(item.Fields))
	} else {
		fmt.Fprintf(b, "\tdst = cbor.AppendMapHeader(dst, %d)\n", len(item.Fields))
	}
	for _, field := range item.Fields {
		if item.Profile == CborWorld {
			if item.IntKeys {
				fmt.Fprintf(b, "\tdst = cbor.AppendUint(dst, %d)\n", field.IntKey)
			} else {
				fmt.Fprintf(b, "\tdst = cbor.AppendText(dst, %q)\n", field.Key)
			}
		}
		cborAppendValue(b, "v."+field.Name, field.Type, item.Profile, 1, 0)
	}
	b.WriteString("\treturn dst\n}\n\n")
}

// appendValue writes one value into dst.
func cborAppendValue(b *bytes.Buffer, expr string, t CborType, profile CborProfile, indent, depth int) {
	tab := strings.Repeat("\t", indent)
	switch t.Kind {
	case CborUint:
		fmt.Fprintf(b, "%sdst = cbor.AppendUint(dst, uint64(%s))\n", tab, expr)
	case CborInt:
		fmt.Fprintf(b, "%sdst = cbor.AppendInt(dst, int64(%s))\n", tab, expr)
	case CborBool:
		fmt.Fprintf(b, "%sdst = cbor.AppendBool(dst, bool(%s))\n", tab, expr)
	case CborText:
		fmt.Fprintf(b, "%sdst = cbor.AppendText(dst, string(%s))\n", tab, expr)
	case CborBytes:
		fmt.Fprintf(b, "%sdst = cbor.AppendBytes(dst, []byte(%s))\n", tab, expr)
	case CborSelf:
		// The type carries its own encoding, so this is the one call. It is
		// resolved here rather than at run time: no type switch, no assertion.
		fmt.Fprintf(b, "%sdst = %s.AppendCBORTo(dst)\n", tab, expr)
	case CborStruct:
		fmt.Fprintf(b, "%sdst = %s(dst, %s)\n", tab,
			cborAppendFuncName(CborTypePlan{Name: t.Struct, Profile: profile}), expr)
	case CborSlice:
		i := fmt.Sprintf("i%d", depth)
		fmt.Fprintf(b, "%sdst = cbor.AppendArrayHeader(dst, len(%s))\n", tab, expr)
		fmt.Fprintf(b, "%sfor %s := range %s {\n", tab, i, expr)
		cborAppendValue(b, fmt.Sprintf("%s[%s]", expr, i), *t.Elem, profile, indent+1, depth+1)
		fmt.Fprintf(b, "%s}\n", tab)
	}
}

// appendMethod publishes the encoder as the driver's cbor.Appender.
//
// The interface is the driver's and is not restated anywhere in tinybind: two
// spellings of one contract means a type can satisfy the wrong one and be
// skipped without a word.
func (e *cborEmitter) appendMethod(item CborTypePlan) {
	b := &e.body
	fmt.Fprintf(b, "// AppendCBORTo appends v as one %s-profile CBOR item, satisfying cbor.Appender.\n",
		item.Profile)
	fmt.Fprintf(b, "func (v %s) AppendCBORTo(dst []byte) []byte {\n\treturn %s(dst, v)\n}\n\n",
		item.Name, cborAppendFuncName(item))
}

// writeWholeCollections says which collections a delta carries whole.
//
// A collection whose element type declares no identity cannot be diffed, so it
// is sent entire under one bit. That is legal, and for a short fixed slice it
// is cheaper than diffing. For an entity list it produces deltas the size of a
// snapshot, which looks exactly like the feature working -- so the decision is
// written down here, where a review sees it.
func (e *cborEmitter) writeWholeCollections(out *bytes.Buffer) {
	if len(e.plan.WholeCollections) == 0 {
		return
	}
	out.WriteString("// The collections below are carried whole by a delta, because their element\n" +
		"// type declares no cbor:\",identity\" field. Declare one to diff them element\n" +
		"// by element:\n//\n")
	for _, name := range e.plan.WholeCollections {
		fmt.Fprintf(out, "//\t%s\n", name)
	}
	out.WriteString("\n")
}

// writeHelpers emits the delta types and functions in name order, so the file
// does not depend on the order the walk met them in.
func (e *cborEmitter) writeHelpers(out *bytes.Buffer) {
	names := make([]string, 0, len(e.helpers))
	for name := range e.helpers {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		out.WriteString(e.helpers[name])
	}
}
