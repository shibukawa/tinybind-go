// emitEncode writes the document straight into a byte slice. The previous
// shape built a map[string]any and handed it to encoding/json, which boxed
// every scalar and then reflected over the result; appending literal key bytes
// costs nothing at run time and lets the whole encode run allocation-free.
//
// One visible consequence: members come out in struct field order rather than
// the sorted order a map produced.
//
// Separators are the one thing omitempty and omitzero complicate. A model with
// no such tag knows at generation time which member is first, so every comma is
// baked into the key bytes. Once a member can drop out, the comma before the
// next one is only knowable at run time — but only until some member is written
// unconditionally, after which every later comma is certain again. The `wrote`
// flag below covers exactly that opening stretch and is declared only when a
// member actually consults it.
func emitEncode(b *bytes.Buffer, t TypePlan, types map[string]TypePlan) {
	members := jsonMembers(t)
	var rest []FieldPlan
	for _, f := range t.Fields {
		if f.IsRest() {
			rest = append(rest, f)
		}
	}

	fmt.Fprintf(b, "func append%sJSON(dst []byte, v %s) []byte {\n", t.Name, t.Name)
	b.WriteString("\tdst = append(dst, '{')\n")

	flagged := needsWroteFlag(members, len(rest) > 0)
	if flagged {
		b.WriteString("\twrote := false\n")
	}

	certain := false
	for i, f := range members {
		key := f.JSON
		if key == "" {
			key = f.Wire
		}
		cond := omitCondition(f, "v."+f.Name)
		prefix := "\t"
		if cond != "" {
			fmt.Fprintf(b, "\tif %s {\n", cond)
			prefix = "\t\t"
		}
		switch {
		case i == 0:
			// Nothing can precede the first member, so it never leads with a comma.
			fmt.Fprintf(b, "%sdst = append(dst, %s...)\n", prefix, strconv.Quote(strconv.Quote(key)+":"))
		case certain:
			fmt.Fprintf(b, "%sdst = append(dst, %s...)\n", prefix, strconv.Quote(","+strconv.Quote(key)+":"))
		default:
			fmt.Fprintf(b, "%sif wrote {\n%s\tdst = append(dst, ',')\n%s}\n", prefix, prefix, prefix)
			fmt.Fprintf(b, "%sdst = append(dst, %s...)\n", prefix, strconv.Quote(strconv.Quote(key)+":"))
		}
		emitAppendValue(b, f, prefix, "v."+f.Name)
		if cond == "" {
			certain = true
			continue
		}
		// Only worth recording when something still to come will ask: the next
		// member reads it while nothing is certain yet, and a rest map reads it
		// after the last one.
		if flagged && !certain && (i < len(members)-1 || len(rest) > 0) {
			fmt.Fprintf(b, "%swrote = true\n", prefix)
		}
		b.WriteString("\t}\n")
	}

	for _, f := range rest {
		emitAppendRest(b, f, restLead(len(members), certain, flagged))
	}

	b.WriteString("\treturn append(dst, '}')\n}\n\n")

	fmt.Fprintf(b, "func encode%s(w io.Writer, v %s) error {\n", t.Name, t.Name)
	b.WriteString("\tbuf := jsonbind.GetBuffer()\n")
	fmt.Fprintf(b, "\t*buf = append%sJSON((*buf)[:0], v)\n", t.Name)
	b.WriteString("\t*buf = append(*buf, '\\n')\n")
	b.WriteString("\t_, err := w.Write(*buf)\n")
	b.WriteString("\tjsonbind.PutBuffer(buf)\n")
	b.WriteString("\treturn err\n}\n\n")
	_ = types
}

// jsonMembers lists the fields the encoder writes as named members, in
// declaration order: everything but a rest map and the fields json:"-" removes
// from the document altogether.
func jsonMembers(t TypePlan) []FieldPlan {
	var out []FieldPlan
	for _, f := range t.Fields {
		if f.IsRest() || f.JSONSkip {
			continue
		}
		out = append(out, f)
	}
	return out
}

// needsWroteFlag reports whether the encoder has to remember at run time that
// something was written. It does when some member's leading comma cannot be
// settled at generation time, which happens only while every member so far
// could have dropped out.
func needsWroteFlag(members []FieldPlan, hasRest bool) bool {
	certain := false
	for i, f := range members {
		if i > 0 && !certain {
			return true
		}
		if omitCondition(f, "x") == "" {
			certain = true
		}
	}
	return hasRest && len(members) > 0 && !certain
}

// restLead is how a rest map decides on the comma before each of its members.
func restLead(members int, certain, flagged bool) string {
	switch {
	case certain:
		return "always"
	case members > 0 && flagged:
		return "wrote"
	default:
		return "first"
	}
}

// omitCondition is the expression that must hold for a field to be written, or
// "" when it is written unconditionally.
//
// omitempty follows encoding/json/v2 rather than encoding/json: it asks whether
// the member would encode as an empty JSON value, so it reaches "", [] and {}
// and leaves 0 and false alone. omitzero is the one that drops a zero number or
// a false flag. Both together mean either can drop the member.
func omitCondition(f FieldPlan, src string) string {
	empty := ""
	if f.OmitEmpty {
		empty = notEmptyExpr(f, src)
	}
	zero := ""
	if f.OmitZero {
		zero = notZeroExpr(f, src)
	}
	switch {
	case empty == "" || zero == "" || empty == zero:
		return empty + zero
	case f.Kind == KindSlice || f.Kind == KindMap:
		// A non-empty slice or map is never the nil one, so asking both would
		// only spell the same test twice.
		return empty
	default:
		return empty + " && " + zero
	}
}

// notEmptyExpr is true when the field would not encode as an empty JSON value.
// Numbers, booleans and nested objects have no empty form, so they carry no
// condition and omitempty is inert on them.
func notEmptyExpr(f FieldPlan, src string) string {
	switch f.Kind {
	case "string":
		return src + ` != ""`
	case KindSlice, KindMap:
		return "len(" + src + ") > 0"
	default:
		return ""
	}
}

// notZeroExpr is true when the field holds something other than its Go zero
// value. A nested struct delegates to the generated isZero helper for its type.
// It is the negation of zeroExpr, spelled directly rather than wrapped in a !()
// so that the generated line reads the way it would if it were written by hand.
func notZeroExpr(f FieldPlan, src string) string {
	switch f.Kind {
	case "string":
		return src + ` != ""`
	case "int", "int64", "float64":
		return src + " != 0"
	case "bool":
		return src
	case KindSlice, KindMap, KindRestAny, KindRestRaw:
		return src + " != nil"
	case KindStruct:
		return "!isZero" + f.TypeName + "(" + src + ")"
	case "file":
		return "!(" + zeroExpr(f, src) + ")"
	default:
		return ""
	}
}

// zeroExpr is the test for a field holding its Go zero value, which is what
// omitzero asks and what an isZero helper is built out of. Reading it in the
// positive keeps the nested case honest: a struct is zero when every one of its
// fields is, and that conjunction is what has to be negated as a whole.
func zeroExpr(f FieldPlan, src string) string {
	switch f.Kind {
	case "string":
		return src + ` == ""`
	case "int", "int64", "float64":
		return src + " == 0"
	case "bool":
		return "!" + src
	case KindSlice, KindMap, KindRestAny, KindRestRaw:
		return src + " == nil"
	case KindStruct:
		return "isZero" + f.TypeName + "(" + src + ")"
	case "file":
		// httpbind.File holds a []byte, so it is not comparable and the zero
		// value has to be spelled out a field at a time.
		return src + `.Filename == "" && ` + src + `.ContentType == "" && ` + src + ".Size == 0 && " + src + ".Content == nil"
	default:
		return ""
	}
}

// zeroCheckedTypes names the struct types that need an isZero helper: the ones
// an omitzero field asks about, plus the ones those reach through struct fields
// of their own, since a struct is zero only when its members all are.
func zeroCheckedTypes(plans []TypePlan) map[string]bool {
	byName := make(map[string]TypePlan, len(plans))
	for _, t := range plans {
		byName[t.Name] = t
	}
	need := map[string]bool{}
	var walk func(string)
	walk = func(name string) {
		t, ok := byName[name]
		if !ok || need[name] {
			return
		}
		need[name] = true
		for _, f := range t.Fields {
			if f.Kind == KindStruct {
				walk(f.TypeName)
			}
		}
	}
	for _, t := range plans {
		for _, f := range t.Fields {
			if f.OmitZero && f.Kind == KindStruct {
				walk(f.TypeName)
			}
		}
	}
	return need
}

// emitZeroCheck writes the helper omitzero uses on a nested struct.
// encoding/json/v2 compares the field against its type's zero value; a struct
// carrying a slice or a map is not comparable in Go, so the same question is
// asked one member at a time instead.
func emitZeroCheck(b *bytes.Buffer, t TypePlan) {
	var conds []string
	for _, f := range t.Fields {
		if c := zeroExpr(f, "v."+f.Name); c != "" {
			conds = append(conds, c)
		}
	}
	fmt.Fprintf(b, "func isZero%s(v %s) bool {\n", t.Name, t.Name)
	if len(conds) == 0 {
		fmt.Fprintf(b, "\t_ = v\n\treturn true\n}\n\n")
		return
	}
	fmt.Fprintf(b, "\treturn %s\n}\n\n", strings.Join(conds, " && "))
}

// emitAppendValue appends one field value to dst.
func emitAppendValue(b *bytes.Buffer, f FieldPlan, prefix, src string) {
	switch f.Kind {
	case "string":
		fmt.Fprintf(b, "%sdst = jsonbind.AppendString(dst, %s)\n", prefix, src)
	case "int":
		fmt.Fprintf(b, "%sdst = jsonbind.AppendInt(dst, int64(%s))\n", prefix, src)
	case "int64":
		fmt.Fprintf(b, "%sdst = jsonbind.AppendInt(dst, %s)\n", prefix, src)
	case "bool":
		fmt.Fprintf(b, "%sdst = jsonbind.AppendBool(dst, %s)\n", prefix, src)
	case "float64":
		fmt.Fprintf(b, "%sdst = jsonbind.AppendFloat(dst, %s)\n", prefix, src)
	case "file":
		fmt.Fprintf(b, "%sdst = httpbind.AppendFileJSON(dst, %s)\n", prefix, src)
	case KindStruct:
		fmt.Fprintf(b, "%sdst = append%sJSON(dst, %s)\n", prefix, f.TypeName, src)
	case KindForeign:
		// The type carries its own encoder, so there is no generated function
		// to name. Appending into the same destination is what lets this
		// compose at any depth for free.
		fmt.Fprintf(b, "%sdst = %s.AppendJSONTo(dst)\n", prefix, src)
	case KindSlice:
		// A nil slice encodes as [], the way encoding/json/v2 writes one.
		// encoding/json wrote null, which asked a client to tell "no items"
		// apart from "an empty list" along a line the Go type never drew.
		// The nil case needs nothing of its own: ranging over a nil slice
		// yields nothing, so the brackets come out empty by themselves.
		fmt.Fprintf(b, "%sdst = append(dst, '[')\n", prefix)
		fmt.Fprintf(b, "%sfor i := range %s {\n", prefix, src)
		fmt.Fprintf(b, "%s\tif i > 0 {\n%s\t\tdst = append(dst, ',')\n%s\t}\n", prefix, prefix, prefix)
		emitAppendValue(b, FieldPlan{Kind: f.ElemKind, TypeName: f.TypeName}, prefix+"\t\t", src+"[i]")
		fmt.Fprintf(b, "%s}\n", prefix)
		fmt.Fprintf(b, "%sdst = append(dst, ']')\n", prefix)
	case KindMap:
		// Same rule as the slice above: a nil map is {}, not null. SortedKeys
		// hands back an empty list for one, so the braces close on their own.
		fmt.Fprintf(b, "%sdst = append(dst, '{')\n", prefix)
		fmt.Fprintf(b, "%sfor i, k := range jsonbind.SortedKeys(%s) {\n", prefix, src)
		fmt.Fprintf(b, "%s\tif i > 0 {\n%s\t\tdst = append(dst, ',')\n%s\t}\n", prefix, prefix, prefix)
		fmt.Fprintf(b, "%s\tdst = jsonbind.AppendString(dst, k)\n", prefix)
		fmt.Fprintf(b, "%s\tdst = append(dst, ':')\n", prefix)
		emitAppendValue(b, FieldPlan{Kind: f.ElemKind, TypeName: f.TypeName}, prefix+"\t", src+"[k]")
		fmt.Fprintf(b, "%s}\n", prefix)
		fmt.Fprintf(b, "%sdst = append(dst, '}')\n", prefix)
	default:
		fmt.Fprintf(b, "%sdst = append(dst, \"null\"...)\n", prefix)
	}
}

// emitAppendRest appends a payload:"*" map. Keys are sorted so a response is
// reproducible, which is what the map-based encoder gave for free. lead says
// how each member decides on its leading comma: "always" when a declared member
// is certainly in front of it, "first" when nothing is, and "wrote" when only
// omittable members are and the answer waits until run time.
func emitAppendRest(b *bytes.Buffer, f FieldPlan, lead string) {
	switch lead {
	case "always":
		fmt.Fprintf(b, "\tfor _, k := range jsonbind.SortedKeys(v.%s) {\n", f.Name)
		b.WriteString("\t\tdst = append(dst, ',')\n")
	case "wrote":
		fmt.Fprintf(b, "\tfor i, k := range jsonbind.SortedKeys(v.%s) {\n", f.Name)
		b.WriteString("\t\tif wrote || i > 0 {\n\t\t\tdst = append(dst, ',')\n\t\t}\n")
	default:
		fmt.Fprintf(b, "\tfor i, k := range jsonbind.SortedKeys(v.%s) {\n", f.Name)
		b.WriteString("\t\tif i > 0 {\n\t\t\tdst = append(dst, ',')\n\t\t}\n")
	}
	b.WriteString("\t\tdst = jsonbind.AppendString(dst, k)\n")
	b.WriteString("\t\tdst = append(dst, ':')\n")
	switch f.Kind {
	case KindRestRaw:
		fmt.Fprintf(b, "\t\tdst = jsonbind.AppendRaw(dst, v.%s[k])\n", f.Name)
	default:
		fmt.Fprintf(b, "\t\tdst = jsonbind.AppendAny(dst, v.%s[k])\n", f.Name)
	}
	b.WriteString("\t}\n")
}

func emitBinder(b *bytes.Buffer, t TypePlan, types map[string]TypePlan, target transportTarget) {
	fmt.Fprintf(b, "func bind%s(%s) (%s, error) {\n", t.Name, target.binderParams, t.Name)
	fmt.Fprintf(b, "\tvar out %s\n", t.Name)

	hasChecks := false
	for _, f := range t.Fields {
		if f.NeedsPresence() {
			hasChecks = true
			fmt.Fprintf(b, "\tvar present%s bool\n", f.Name)
		}
	}

	needsBody := false
	needsFiles := false
	needsForm := false // formBody used for scalar/rest fields
	needsQuery := false
	for _, f := range t.Fields {
		if (f.Source == SourceQuery || f.Source == SourceInput) && !f.IsComposite() {
			needsQuery = true
		}
		if f.Source == SourceInput || f.Source == SourcePayload {
			needsBody = true
			if f.Kind == "file" {
				needsFiles = true
			} else if f.IsRest() || !f.IsComposite() {
				needsForm = true
			}
		}
	}
	if needsQuery {
		b.WriteString("\tqueryVals := httpbind.Queries(r)\n")
	}
	if needsBody {
		b.WriteString("\tvar jsonBody *jsonbind.Object\n")
		if needsForm || needsFiles {
			b.WriteString("\tvar formBody map[string]string\n")
		}
		if needsFiles {
			b.WriteString("\tvar fileBody map[string]httpbind.File\n")
		}
		b.WriteString("\tvar bodyRead bool\n")
		b.WriteString("\treadBody := func() error {\n")
		b.WriteString("\t\tif bodyRead {\n\t\t\treturn nil\n\t\t}\n")
		b.WriteString("\t\tbodyRead = true\n")
		b.WriteString("\t\tvar err error\n")
		switch {
		case needsFiles:
			fmt.Fprintf(b, "\t\tjsonBody, formBody, fileBody, err = httpbind.ReadBody(r, %t, true)\n", needsForm)
		case needsForm:
			b.WriteString("\t\tjsonBody, formBody, _, err = httpbind.ReadBody(r, true, false)\n")
		default:
			b.WriteString("\t\tjsonBody, _, _, err = httpbind.ReadBody(r, false, false)\n")
		}
		b.WriteString("\t\treturn err\n")
		b.WriteString("\t}\n")
	}

	for _, f := range t.Fields {
		if f.IsRest() {
			continue
		}
		emitFieldBind(b, f, types)
	}
	for _, f := range t.Fields {
		if f.IsRest() {
			emitRestField(b, t, f)
		}
	}

	if hasChecks {
		emitValidate(b, t)
		emitDefaults(b, t)
	}
	b.WriteString("\treturn out, nil\n}\n\n")
}

func bodyWireExclude(t TypePlan) []string {
	var out []string
	for _, f := range t.Fields {
		if f.IsRest() {
			continue
		}
		if f.Source == SourcePayload || f.Source == SourceInput {
			if f.Wire != "" && f.Wire != "*" {
				out = append(out, f.Wire)
			}
		}
	}
	return out
}

func emitRestField(b *bytes.Buffer, t TypePlan, f FieldPlan) {
	exclude := bodyWireExclude(t)
	b.WriteString("\tif err := readBody(); err != nil {\n\t\treturn out, err\n\t}\n")
	fmt.Fprintf(b, "\tif jsonBody != nil {\n")
	switch f.Kind {
	case KindRestAny:
		fmt.Fprintf(b, "\t\tm, err := jsonbind.RestJSONAny(jsonBody, []string{%s})\n", quoteStringList(exclude))
		b.WriteString("\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n")
		fmt.Fprintf(b, "\t\tout.%s = m\n", f.Name)
	case KindRestRaw:
		fmt.Fprintf(b, "\t\tout.%s = map[string]json.RawMessage{}\n", f.Name)
		b.WriteString("\t\tfor i := 0; i < jsonBody.Len(); i++ {\n")
		fmt.Fprintf(b, "\t\t\tk, raw, ok := jsonbind.RestJSONMember(jsonBody, i, []string{%s})\n", quoteStringList(exclude))
		b.WriteString("\t\t\tif !ok {\n\t\t\t\tcontinue\n\t\t\t}\n")
		fmt.Fprintf(b, "\t\t\tout.%s[k] = append(json.RawMessage(nil), raw...)\n", f.Name)
		b.WriteString("\t\t}\n")
	}
	fmt.Fprintf(b, "\t} else if formBody != nil {\n")
	switch f.Kind {
	case KindRestAny:
		fmt.Fprintf(b, "\t\tout.%s = httpbind.RestFormAny(formBody, []string{%s})\n", f.Name, quoteStringList(exclude))
	case KindRestRaw:
		fmt.Fprintf(b, "\t\tout.%s = httpbind.RestFormRaw(formBody, []string{%s})\n", f.Name, quoteStringList(exclude))
	}
	fmt.Fprintf(b, "\t} else {\n")
	switch f.Kind {
	case KindRestAny:
		fmt.Fprintf(b, "\t\tout.%s = map[string]any{}\n", f.Name)
	case KindRestRaw:
		fmt.Fprintf(b, "\t\tout.%s = map[string]json.RawMessage{}\n", f.Name)
	}
	b.WriteString("\t}\n")
}

func quoteStringList(ss []string) string {
	if len(ss) == 0 {
		return ""
	}
	var b strings.Builder
	for i, s := range ss {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(s))
	}
	return b.String()
}

func emitFieldBind(b *bytes.Buffer, f FieldPlan, types map[string]TypePlan) {
	track := f.NeedsPresence()
	switch f.Source {
	case SourcePath:
		if f.Kind == "string" {
			fmt.Fprintf(b, "\tout.%s = httpbind.PathValue(r, %q)\n", f.Name, f.Wire)
			if track {
				fmt.Fprintf(b, "\tif out.%s != \"\" {\n\t\tpresent%s = true\n\t}\n", f.Name, f.Name)
			}
		} else if !f.IsComposite() && f.Kind != "file" {
			fmt.Fprintf(b, "\tif pv := httpbind.PathValue(r, %q); pv != \"\" {\n", f.Wire)
			if track {
				fmt.Fprintf(b, "\t\tpresent%s = true\n", f.Name)
			}
			emitConvertFromStringIndented(b, f, "pv", "path", "\t\t")
			b.WriteString("\t}\n")
		}
	case SourceHeader:
		if f.Kind == "string" {
			fmt.Fprintf(b, "\tout.%s = httpbind.HeaderValue(r, %q)\n", f.Name, f.Wire)
			if track {
				fmt.Fprintf(b, "\tif out.%s != \"\" {\n\t\tpresent%s = true\n\t}\n", f.Name, f.Name)
			}
		} else if !f.IsComposite() && f.Kind != "file" {
			fmt.Fprintf(b, "\tif hv := httpbind.HeaderValue(r, %q); hv != \"\" {\n", f.Wire)
			if track {
				fmt.Fprintf(b, "\t\tpresent%s = true\n", f.Name)
			}
			emitConvertFromStringIndented(b, f, "hv", "header", "\t\t")
			b.WriteString("\t}\n")
		}
	case SourceCookie:
		if !f.IsComposite() {
			fmt.Fprintf(b, "\tif cv, ok := httpbind.CookieValue(r, %q); ok {\n", f.Wire)
			if track {
				fmt.Fprintf(b, "\t\tpresent%s = true\n", f.Name)
			}
			emitConvertFromStringIndented(b, f, "cv", "cookie", "\t\t")
			b.WriteString("\t}\n")
		}
	case SourceMethod:
		if f.Kind == "string" {
			fmt.Fprintf(b, "\tout.%s = r.Method\n", f.Name)
			if track {
				fmt.Fprintf(b, "\tpresent%s = true\n", f.Name)
			}
		}
	case SourceQuery:
		if !f.IsComposite() {
			fmt.Fprintf(b, "\tif qv, ok := httpbind.QueryLookup(queryVals, %q); ok {\n", f.Wire)
			if track {
				fmt.Fprintf(b, "\t\tpresent%s = true\n", f.Name)
			}
			emitConvertFromStringIndented(b, f, "qv", "query", "\t\t")
			b.WriteString("\t}\n")
		}
	case SourcePayload:
		emitPayloadField(b, f, types, "\t", track)
	case SourceInput:
		if f.IsComposite() {
			// Nested only from body for input-tagged composites.
			emitPayloadField(b, f, types, "\t", track)
			return
		}
		fmt.Fprintf(b, "\tif qv, ok := httpbind.QueryLookup(queryVals, %q); ok {\n", f.Wire)
		if track {
			fmt.Fprintf(b, "\t\tpresent%s = true\n", f.Name)
		}
		emitConvertFromStringIndented(b, f, "qv", "query", "\t\t")
		b.WriteString("\t} else {\n")
		emitPayloadField(b, f, types, "\t\t", track)
		b.WriteString("\t}\n")
	}
}

func emitPayloadField(b *bytes.Buffer, f FieldPlan, types map[string]TypePlan, prefix string, track bool) {
	fmt.Fprintf(b, "%sif err := readBody(); err != nil {\n%s\treturn out, err\n%s}\n", prefix, prefix, prefix)
	if f.Kind == "file" {
		fmt.Fprintf(b, "%sif fv, ok := fileBody[%q]; ok {\n", prefix, f.Wire)
		if track {
			fmt.Fprintf(b, "%s\tpresent%s = true\n", prefix, f.Name)
		}
		fmt.Fprintf(b, "%s\tout.%s = fv\n", prefix, f.Name)
		fmt.Fprintf(b, "%s} else if fileBody != nil {\n", prefix)
		fmt.Fprintf(b, "%s\treturn out, httpbind.BindError(%q, \"payload\", \"missing file\")\n", prefix, f.Wire)
		fmt.Fprintf(b, "%s}\n", prefix)
		return
	}
	// JSON path (including nested)
	fmt.Fprintf(b, "%sif raw, ok := jsonBody.Get(%q); ok {\n", prefix, f.Wire)
	if track {
		fmt.Fprintf(b, "%s\tpresent%s = true\n", prefix, f.Name)
	}
	emitAssignFromRaw(b, f, types, "raw", prefix+"\t", "out."+f.Name, true)
	if f.IsComposite() {
		fmt.Fprintf(b, "%s}\n", prefix)
		return
	}
	// form only for scalars
	fmt.Fprintf(b, "%s} else if formBody != nil {\n", prefix)
	fmt.Fprintf(b, "%s\tif fv, ok := formBody[%q]; ok {\n", prefix, f.Wire)
	if track {
		fmt.Fprintf(b, "%s\t\tpresent%s = true\n", prefix, f.Name)
	}
	emitConvertFromStringIndented(b, f, "fv", "payload", prefix+"\t\t")
	fmt.Fprintf(b, "%s\t}\n", prefix)
	fmt.Fprintf(b, "%s}\n", prefix)
}

func emitConvertFromStringIndented(b *bytes.Buffer, f FieldPlan, varName, location, prefix string) {
	switch f.Kind {
	case "int":
		fmt.Fprintf(b, "%sv, err := httpbind.ParseInt(%s)\n", prefix, varName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, httpbind.BindError(%q, %q, \"invalid int\")\n%s}\n", prefix, prefix, f.Wire, location, prefix)
		fmt.Fprintf(b, "%sout.%s = v\n", prefix, f.Name)
	case "int64":
		fmt.Fprintf(b, "%sv, err := httpbind.ParseInt64(%s)\n", prefix, varName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, httpbind.BindError(%q, %q, \"invalid int64\")\n%s}\n", prefix, prefix, f.Wire, location, prefix)
		fmt.Fprintf(b, "%sout.%s = v\n", prefix, f.Name)
	case "bool":
		fmt.Fprintf(b, "%sv, err := httpbind.ParseBool(%s)\n", prefix, varName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, httpbind.BindError(%q, %q, \"invalid bool\")\n%s}\n", prefix, prefix, f.Wire, location, prefix)
		fmt.Fprintf(b, "%sout.%s = v\n", prefix, f.Name)
	case "float64":
		fmt.Fprintf(b, "%sv, err := httpbind.ParseFloat64(%s)\n", prefix, varName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, httpbind.BindError(%q, %q, \"invalid float64\")\n%s}\n", prefix, prefix, f.Wire, location, prefix)
		fmt.Fprintf(b, "%sout.%s = v\n", prefix, f.Name)
	case "string":
		fmt.Fprintf(b, "%sout.%s = %s\n", prefix, f.Name, varName)
	}
}

func emitValidate(b *bytes.Buffer, t TypePlan) {
	b.WriteString("\tvar checkFields []httpbind.FieldError\n")
	for _, f := range t.Fields {
		if !f.HasValidation() {
			continue
		}
		loc := checkLocation(f.Source)
		c := f.Check
		if c.Required {
			switch f.Kind {
			case "string":
				fmt.Fprintf(b, "\tif !present%s || out.%s == \"\" {\n", f.Name, f.Name)
			case "file":
				fmt.Fprintf(b, "\tif !present%s || out.%s.Empty() {\n", f.Name, f.Name)
			default:
				fmt.Fprintf(b, "\tif !present%s {\n", f.Name)
			}
			fmt.Fprintf(b, "\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"required\"))\n", f.Wire, loc)
			b.WriteString("\t}\n")
		}

		hasValueConstraints := c.Min != nil || c.Max != nil ||
			c.MinLen != nil || c.MaxLen != nil || c.Len != nil ||
			f.Enum.Set || c.Email || c.UUID || c.Date || c.Time || c.DateTime || c.Pattern != ""
		if hasValueConstraints {
			fmt.Fprintf(b, "\tif present%s {\n", f.Name)
			if c.Min != nil {
				switch f.Kind {
				case "int":
					fmt.Fprintf(b, "\t\tif out.%s < %s {\n", f.Name, intLit(*c.Min))
				case "int64":
					fmt.Fprintf(b, "\t\tif out.%s < %s {\n", f.Name, int64Lit(*c.Min))
				case "float64":
					fmt.Fprintf(b, "\t\tif out.%s < %s {\n", f.Name, floatLit(*c.Min))
				}
				fmt.Fprintf(b, "\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, fmt.Sprintf("must be >= %v", numMsg(*c.Min)))
				b.WriteString("\t\t}\n")
			}
			if c.Max != nil {
				switch f.Kind {
				case "int":
					fmt.Fprintf(b, "\t\tif out.%s > %s {\n", f.Name, intLit(*c.Max))
				case "int64":
					fmt.Fprintf(b, "\t\tif out.%s > %s {\n", f.Name, int64Lit(*c.Max))
				case "float64":
					fmt.Fprintf(b, "\t\tif out.%s > %s {\n", f.Name, floatLit(*c.Max))
				}
				fmt.Fprintf(b, "\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, fmt.Sprintf("must be <= %v", numMsg(*c.Max)))
				b.WriteString("\t\t}\n")
			}
			if f.Kind == "string" {
				if c.MinLen != nil {
					fmt.Fprintf(b, "\t\tif len(out.%s) < %d {\n", f.Name, *c.MinLen)
					fmt.Fprintf(b, "\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, fmt.Sprintf("length must be >= %d", *c.MinLen))
					b.WriteString("\t\t}\n")
				}
				if c.MaxLen != nil {
					fmt.Fprintf(b, "\t\tif len(out.%s) > %d {\n", f.Name, *c.MaxLen)
					fmt.Fprintf(b, "\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, fmt.Sprintf("length must be <= %d", *c.MaxLen))
					b.WriteString("\t\t}\n")
				}
				if c.Len != nil {
					fmt.Fprintf(b, "\t\tif len(out.%s) != %d {\n", f.Name, *c.Len)
					fmt.Fprintf(b, "\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, fmt.Sprintf("length must be %d", *c.Len))
					b.WriteString("\t\t}\n")
				}
			}
			if f.Enum.Set {
				b.WriteString("\t\t{\n")
				b.WriteString("\t\t\tenumOK := false\n")
				for _, v := range f.Enum.Values {
					lit, _ := defaultGoLiteral(f.Kind, v)
					fmt.Fprintf(b, "\t\t\tif out.%s == %s {\n\t\t\t\tenumOK = true\n\t\t\t}\n", f.Name, lit)
				}
				b.WriteString("\t\t\tif !enumOK {\n")
				msg := "must be one of: " + joinEnumMsg(f.Enum.Values)
				fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, %q))\n", f.Wire, loc, msg)
				b.WriteString("\t\t\t}\n")
				b.WriteString("\t\t}\n")
			}
			if f.Kind == "string" && (c.Email || c.UUID || c.Date || c.Time || c.DateTime || c.Pattern != "") {
				fmt.Fprintf(b, "\t\tif out.%s != \"\" {\n", f.Name)
				if c.Email {
					fmt.Fprintf(b, "\t\t\tif !httpbind.CheckEmail(out.%s) {\n", f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must be a valid email\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				if c.UUID {
					fmt.Fprintf(b, "\t\t\tif !httpbind.CheckUUID(out.%s) {\n", f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must be a valid uuid\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				if c.Date {
					fmt.Fprintf(b, "\t\t\tif !httpbind.CheckDate(out.%s) {\n", f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must be ISO date\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				if c.Time {
					fmt.Fprintf(b, "\t\t\tif !httpbind.CheckTime(out.%s) {\n", f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must be ISO time\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				if c.DateTime {
					fmt.Fprintf(b, "\t\t\tif !httpbind.CheckDateTime(out.%s) {\n", f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must be RFC3339 datetime\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				if c.Pattern != "" {
					fmt.Fprintf(b, "\t\t\tif !checkPattern%s%s.MatchString(out.%s) {\n", t.Name, f.Name, f.Name)
					fmt.Fprintf(b, "\t\t\t\tcheckFields = append(checkFields, httpbind.Field(%q, %q, \"must match pattern\"))\n", f.Wire, loc)
					b.WriteString("\t\t\t}\n")
				}
				b.WriteString("\t\t}\n")
			}
			b.WriteString("\t}\n")
		}
	}
	b.WriteString("\tif len(checkFields) > 0 {\n")
	b.WriteString("\t\treturn out, httpbind.Validation(checkFields...)\n")
	b.WriteString("\t}\n")
}

func emitDefaults(b *bytes.Buffer, t TypePlan) {
	for _, f := range t.Fields {
		if !f.Default.Set {
			continue
		}
		lit, err := defaultGoLiteral(f.Kind, f.Default.Value)
		if err != nil {
			continue
		}
		fmt.Fprintf(b, "\tif !present%s {\n", f.Name)
		fmt.Fprintf(b, "\t\tout.%s = %s\n", f.Name, lit)
		b.WriteString("\t}\n")
	}
}

func joinEnumMsg(vals []string) string {
	return joinComma(vals)
}

func joinComma(vals []string) string {
	if len(vals) == 0 {
		return ""
	}
	out := vals[0]
	for i := 1; i < len(vals); i++ {
		out += ", " + vals[i]
	}
	return out
}

func intLit(f float64) string {
	return strconv.FormatInt(int64(f), 10)
}

func int64Lit(f float64) string {
	return fmt.Sprintf("int64(%d)", int64(f))
}

func floatLit(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 64)
}

func numMsg(f float64) any {
	if f == float64(int64(f)) {
		return int64(f)
	}
	return f
}

func emitWriter(b *bytes.Buffer, t TypePlan, types map[string]TypePlan, target transportTarget) {
	fmt.Fprintf(b, "func write%s(%s, v %s) error {\n", t.Name, target.writerParams, t.Name)
	if target.writerVar != "r" {
		// The request is only there to satisfy the net/http shape; the fasthttp
		// signature has one value and writes through it.
		b.WriteString("\t_ = r\n")
	}
	b.WriteString("\tbuf := jsonbind.GetBuffer()\n")
	fmt.Fprintf(b, "\t*buf = append%sJSON((*buf)[:0], v)\n", t.Name)
	fmt.Fprintf(b, "\terr := httpbind.WriteJSONBytes(%s, http.StatusOK, *buf)\n", target.writerVar)
	b.WriteString("\tjsonbind.PutBuffer(buf)\n")
	b.WriteString("\treturn err\n")
	b.WriteString("}\n\n")
	_ = types
}
