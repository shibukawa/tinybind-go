// Emit generates Go source for type-specific binders, writers, and JSON codecs.
// The output does not import "reflect".
func Emit(plan *PackagePlan) ([]byte, error) {
	return emitSelected(plan, nil)
}

// emitSelected emits only the named subset of plan.Types. The full plan still
// provides nested type lookups, so a per-source artifact can reference helpers
// generated beside another source of the same package. A nil selection emits
// every type.
func emitSelected(plan *PackagePlan, selected map[string]bool) ([]byte, error) {
	if plan == nil {
		return nil, fmt.Errorf("nil plan")
	}
	emitted := make([]TypePlan, 0, len(plan.Types))
	for _, t := range plan.Types {
		if selected == nil || selected[t.Name] {
			emitted = append(emitted, t)
		}
	}
	var b bytes.Buffer
	needRegexp := false
	for _, t := range emitted {
		if t.Usage&UsageBind == 0 {
			continue
		}
		for _, f := range t.Fields {
			if f.Check.Pattern == "" {
				continue
			}
			needRegexp = true
			fmt.Fprintf(&b, "var checkPattern%s%s = regexp.MustCompile(%s)\n", t.Name, f.Name, strconv.Quote(f.Check.Pattern))
		}
	}
	if needRegexp {
		b.WriteString("\n")
	}

	var registrations bytes.Buffer
	for _, t := range emitted {
		if t.DirectUsage&UsageBind != 0 {
			fmt.Fprintf(&registrations, "\thttpbind.RegisterBind[%s](bind%s)\n", t.Name, t.Name)
		}
		if t.DirectUsage&UsageWrite != 0 {
			fmt.Fprintf(&registrations, "\thttpbind.RegisterWrite[%s](write%s)\n", t.Name, t.Name)
		}
		if t.DirectUsage&UsageDecodeJSON != 0 {
			fmt.Fprintf(&registrations, "\tjsonbind.RegisterDecode[%s](decode%sBytes)\n", t.Name, t.Name)
		}
		if t.DirectUsage&UsageEncodeJSON != 0 {
			fmt.Fprintf(&registrations, "\tjsonbind.RegisterEncode[%s](encode%s)\n", t.Name, t.Name)
		}
		if t.DirectUsage&UsageScanRows != 0 {
			fmt.Fprintf(&registrations, "\tsqlbind.RegisterScanRows[%s](scan%sRows)\n", t.Name, t.Name)
		}
	}
	if registrations.Len() > 0 {
		b.WriteString("func init() {\n")
		b.Write(registrations.Bytes())
		b.WriteString("}\n\n")
	}

	// Index types for nested encode helpers
	types := map[string]TypePlan{}
	for _, t := range plan.Types {
		types[t.Name] = t
	}

	for _, t := range emitted {
		if t.Usage&(UsageBind|UsageDecodeJSON) != 0 {
			emitDecodeJSON(&b, t, types)
		}
		if t.Usage&(UsageWrite|UsageEncodeJSON) != 0 {
			emitEncode(&b, t, types)
		}
		if t.Usage&UsageBind != 0 {
			emitBinder(&b, t, types)
		}
		if t.Usage&UsageWrite != 0 {
			emitWriter(&b, t, types)
		}
		if t.DirectUsage&UsageScanRows != 0 {
			if err := emitScanRows(&b, t, types); err != nil {
				return nil, err
			}
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by tinybind; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package %s\n\n", plan.Package)
	writeMappingImports(&out, b.Bytes())
	out.Write(b.Bytes())
	b = out

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("format generated code: %w\n%s", err, b.String())
	}
	return formatted, nil
}

// mappingImports lists every package the mapping emitter can reference,
// together with the qualifier that proves the reference. Grouping keeps
// standard-library imports separated from tinybind imports.
var mappingImports = []struct {
	qualifier string
	path      string
	stdlib    bool
}{
	{qualifier: "json", path: "encoding/json", stdlib: true},
	{qualifier: "io", path: "io", stdlib: true},
	{qualifier: "regexp", path: "regexp", stdlib: true},
	{qualifier: "http", path: "net/http", stdlib: true},
	{qualifier: "sql", path: "database/sql", stdlib: true},
	{qualifier: "httpbind", path: httpbindImportPath},
	{qualifier: "jsonbind", path: jsonbindImportPath},
	{qualifier: "sqlbind", path: sqlbindImportPath},
}

// writeMappingImports emits exactly the imports body references. Deriving them
// from the emitted code keeps every artifact self-contained no matter which
// subset of types or phases produced it.
func writeMappingImports(out *bytes.Buffer, body []byte) {
	var stdlib, tinybind []string
	for _, item := range mappingImports {
		if !usesQualifier(body, item.qualifier) {
			continue
		}
		if item.stdlib {
			stdlib = append(stdlib, item.path)
		} else {
			tinybind = append(tinybind, item.path)
		}
	}
	if len(stdlib)+len(tinybind) == 0 {
		return
	}
	out.WriteString("import (\n")
	for _, path := range stdlib {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	if len(stdlib) > 0 && len(tinybind) > 0 {
		out.WriteString("\n")
	}
	for _, path := range tinybind {
		fmt.Fprintf(out, "\t%q\n", path)
	}
	out.WriteString(")\n\n")
}

// usesQualifier reports whether body contains a "<qualifier>." selector that is
// not the tail of a longer identifier.
func usesQualifier(body []byte, qualifier string) bool {
	needle := []byte(qualifier + ".")
	for offset := 0; ; {
		index := bytes.Index(body[offset:], needle)
		if index < 0 {
			return false
		}
		at := offset + index
		if at == 0 || !isIdentifierByte(body[at-1]) {
			return true
		}
		offset = at + 1
	}
}

func isIdentifierByte(c byte) bool {
	return c == '_' || (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
}

func emitScanRows(b *bytes.Buffer, root TypePlan, types map[string]TypePlan) error {
	key, err := sqlGroupKey(root)
	if err != nil {
		return fmt.Errorf("%s: %w", root.Name, err)
	}
	fmt.Fprintf(b, "func scan%sRows(rows *sql.Rows) ([]%s, error) {\n", root.Name, root.Name)
	fmt.Fprintf(b, "\tout := []%s{}\n\trootIndexes := map[string]int{}\n", root.Name)
	if err := emitSQLIndexDecls(b, root, types, root.Name, "\t"); err != nil {
		return err
	}
	b.WriteString("\terr := sqlbind.ForEach(rows, func(row sqlbind.Row) error {\n")
	fmt.Fprintf(b, "\t\trootKey, err := sqlbind.RequiredKey(row, %q)\n\t\tif err != nil { return err }\n", key.DB)
	b.WriteString("\t\trootPos, exists := rootIndexes[rootKey]\n\t\tif !exists {\n")
	fmt.Fprintf(b, "\t\t\tvar item %s\n", root.Name)
	emitSQLFill(b, root, types, "item", "\t\t\t")
	b.WriteString("\t\t\tout = append(out, item)\n\t\t\trootPos = len(out)-1\n\t\t\trootIndexes[rootKey] = rootPos\n\t\t}\n")
	if err := emitSQLChildren(b, root, types, "out[rootPos]", "rootKey", root.Name, "\t\t"); err != nil {
		return err
	}
	b.WriteString("\t\treturn nil\n\t})\n\tif err != nil { return nil, err }\n\treturn out, nil\n}\n\n")
	return nil
}

func sqlGroupKey(t TypePlan) (FieldPlan, error) {
	var out FieldPlan
	n := 0
	for _, f := range t.Fields {
		if f.GroupKey && !f.IsComposite() {
			out = f
			n++
		}
	}
	if n != 1 {
		return FieldPlan{}, fmt.Errorf("SQL grouped struct must have exactly one scalar groupkey field")
	}
	return out, nil
}

func emitSQLIndexDecls(b *bytes.Buffer, t TypePlan, types map[string]TypePlan, path, prefix string) error {
	for _, f := range t.Fields {
		if f.Kind != KindSlice || f.ElemKind != KindStruct {
			continue
		}
		child, ok := types[f.TypeName]
		if !ok {
			return fmt.Errorf("%s: missing child type %s", t.Name, f.TypeName)
		}
		if _, err := sqlGroupKey(child); err != nil {
			return fmt.Errorf("%s.%s: %w", t.Name, f.Name, err)
		}
		id := sqlIdent(path + f.Name)
		fmt.Fprintf(b, "%s%sIndexes := map[string]int{}\n", prefix, id)
		if err := emitSQLIndexDecls(b, child, types, path+f.Name, prefix); err != nil {
			return err
		}
	}
	return nil
}

func emitSQLFill(b *bytes.Buffer, t TypePlan, types map[string]TypePlan, target, prefix string) {
	for _, f := range t.Fields {
		switch f.Kind {
		case "string", "int", "int64", "bool", "float64":
			fn := strings.ToUpper(f.Kind[:1]) + f.Kind[1:]
			fmt.Fprintf(b, "%sif v, err := sqlbind.%s(row, %q); err != nil { return err } else { %s.%s = v }\n", prefix, fn, f.DB, target, f.Name)
		case KindStruct:
			if child, ok := types[f.TypeName]; ok {
				emitSQLFill(b, child, types, target+"."+f.Name, prefix)
			}
		}
	}
}

func emitSQLChildren(b *bytes.Buffer, t TypePlan, types map[string]TypePlan, target, parentKey, path, prefix string) error {
	for _, f := range t.Fields {
		if f.Kind == KindStruct {
			if child, ok := types[f.TypeName]; ok {
				if err := emitSQLChildren(b, child, types, target+"."+f.Name, parentKey, path+f.Name, prefix); err != nil {
					return err
				}
			}
			continue
		}
		if f.Kind != KindSlice || f.ElemKind != KindStruct {
			continue
		}
		child, ok := types[f.TypeName]
		if !ok {
			return fmt.Errorf("missing SQL child type %s", f.TypeName)
		}
		key, err := sqlGroupKey(child)
		if err != nil {
			return err
		}
		id := sqlIdent(path + f.Name)
		keyVar, presentVar := id+"Key", id+"Present"
		compositeVar, posVar, existsVar := id+"CompositeKey", id+"Pos", id+"Exists"
		fmt.Fprintf(b, "%s%s, %s, err := sqlbind.Key(row, %q)\n%sif err != nil { return err }\n%sif %s {\n", prefix, keyVar, presentVar, key.DB, prefix, prefix, presentVar)
		fmt.Fprintf(b, "%s\t%s := %s + \"\\x00\" + %s\n%s\t%s, %s := %sIndexes[%s]\n%s\tif !%s {\n", prefix, compositeVar, parentKey, keyVar, prefix, posVar, existsVar, id, compositeVar, prefix, existsVar)
		fmt.Fprintf(b, "%s\t\tvar child %s\n", prefix, child.Name)
		emitSQLFill(b, child, types, "child", prefix+"\t\t")
		fmt.Fprintf(b, "%s\t\t%s.%s = append(%s.%s, child)\n%s\t\t%s = len(%s.%s)-1\n%s\t\t%sIndexes[%s] = %s\n%s\t}\n", prefix, target, f.Name, target, f.Name, prefix, posVar, target, f.Name, prefix, id, compositeVar, posVar, prefix)
		if err := emitSQLChildren(b, child, types, target+"."+f.Name+"["+posVar+"]", compositeVar, path+f.Name, prefix+"\t"); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s}\n", prefix)
	}
	return nil
}

func sqlIdent(s string) string {
	var b strings.Builder
	for _, r := range s {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(r)
		}
	}
	return b.String()
}

// emitDecodeJSON writes a decoder that walks the document once. Members are
// dispatched by a switch over the key bytes, and values are read straight out
// of the input buffer, so decoding allocates only what lands in the result.
func emitDecodeJSON(b *bytes.Buffer, t TypePlan, types map[string]TypePlan) {
	fmt.Fprintf(b, "func decode%sBytes(data []byte) (%s, error) {\n", t.Name, t.Name)
	// An empty document has always decoded to the zero value rather than an
	// error. Keep that: callers read config files and optional bodies through
	// here, and turning silence into a failure is not this decoder's call.
	b.WriteString("\tif jsonbind.IsBlank(data) {\n")
	fmt.Fprintf(b, "\t\tvar out %s\n", t.Name)
	for _, f := range t.Fields {
		if f.IsRest() {
			fmt.Fprintf(b, "\t\tout.%s = %s{}\n", f.Name, f.GoType())
		}
	}
	b.WriteString("\t\treturn out, nil\n\t}\n")
	fmt.Fprintf(b, "\tp := jsonbind.NewParser(data)\n")
	fmt.Fprintf(b, "\tout, err := decode%sJSON(p)\n", t.Name)
	b.WriteString("\tif err != nil {\n\t\treturn out, err\n\t}\n")
	b.WriteString("\tif err := p.End(); err != nil {\n\t\treturn out, err\n\t}\n")
	b.WriteString("\treturn out, nil\n}\n\n")

	fmt.Fprintf(b, "func decode%sJSON(p *jsonbind.Parser) (%s, error) {\n", t.Name, t.Name)
	fmt.Fprintf(b, "\tvar out %s\n", t.Name)
	b.WriteString("\tnull, err := p.ObjectStart()\n")
	b.WriteString("\tif err != nil || null {\n\t\treturn out, err\n\t}\n")

	// A rest map is always non-nil once the body is an object, matching what
	// the map-based decoder produced.
	for _, f := range t.Fields {
		if !f.IsRest() {
			continue
		}
		fmt.Fprintf(b, "\tout.%s = %s{}\n", f.Name, f.GoType())
	}

	b.WriteString("\tfor n := 0; ; n++ {\n")
	b.WriteString("\t\tkey, ok, err := p.ObjectKey(n)\n")
	b.WriteString("\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n")
	b.WriteString("\t\tif !ok {\n\t\t\treturn out, nil\n\t\t}\n")
	b.WriteString("\t\tswitch string(key) {\n")

	for _, f := range t.Fields {
		if !isDocumentField(f) || f.IsRest() {
			continue
		}
		key := f.JSON
		if key == "" || key == "*" {
			key = f.Wire
		}
		fmt.Fprintf(b, "\t\tcase %q:\n", key)
		emitStreamAssign(b, f, types, "\t\t\t", "out."+f.Name, 0)
	}

	// Names that belong to the body but decode to nothing here (an uploaded
	// file, say) must still be consumed rather than swept into a rest map.
	for _, name := range skippedBodyNames(t) {
		fmt.Fprintf(b, "\t\tcase %q:\n", name)
		b.WriteString("\t\t\tif err := p.SkipValue(); err != nil {\n\t\t\t\treturn out, err\n\t\t\t}\n")
	}

	b.WriteString("\t\tdefault:\n")
	emitStreamDefault(b, t)
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n}\n\n")
}

// skippedBodyNames lists body field names the streaming decoder must consume
// without storing: they are excluded from rest collection by the map-based
// decoder too, so silently letting them fall through to a rest map would
// change what a payload:"*" field captures.
func skippedBodyNames(t TypePlan) []string {
	var out []string
	for _, f := range t.Fields {
		if f.IsRest() || isDocumentField(f) {
			continue
		}
		if f.Source != SourcePayload && f.Source != SourceInput {
			continue
		}
		if f.Wire == "" || f.Wire == "*" {
			continue
		}
		out = append(out, f.Wire)
	}
	return out
}

// emitStreamDefault handles a member no case matched: collected into a rest
// map when the model declares one, skipped otherwise.
func emitStreamDefault(b *bytes.Buffer, t TypePlan) {
	for _, f := range t.Fields {
		switch f.Kind {
		case KindRestAny:
			b.WriteString("\t\t\tname := string(key)\n")
			b.WriteString("\t\t\tv, err := p.Any()\n")
			b.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn out, err\n\t\t\t}\n")
			fmt.Fprintf(b, "\t\t\tout.%s[name] = v\n", f.Name)
			return
		case KindRestRaw:
			b.WriteString("\t\t\tname := string(key)\n")
			b.WriteString("\t\t\traw, err := p.RawValue()\n")
			b.WriteString("\t\t\tif err != nil {\n\t\t\t\treturn out, err\n\t\t\t}\n")
			// RawValue aliases the input buffer, so a retained value is copied.
			fmt.Fprintf(b, "\t\t\tout.%s[name] = append(json.RawMessage(nil), raw...)\n", f.Name)
			return
		}
	}
	b.WriteString("\t\t\tif err := p.SkipValue(); err != nil {\n\t\t\t\treturn out, err\n\t\t\t}\n")
}

// emitStreamAssign reads one value from the parser into dest. depth keeps
// nested loop variables from shadowing each other.
func emitStreamAssign(b *bytes.Buffer, f FieldPlan, types map[string]TypePlan, prefix, dest string, depth int) {
	switch f.Kind {
	case "string", "int", "int64", "bool", "float64":
		fmt.Fprintf(b, "%sv, err := p.%s()\n", prefix, parserMethod(f.Kind))
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid %s\", err)\n%s}\n", prefix, prefix, f.Wire, f.Kind, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case KindStruct:
		fmt.Fprintf(b, "%sv, err := decode%sJSON(p)\n", prefix, f.TypeName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, err\n%s}\n", prefix, prefix, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case KindSlice:
		if supportedElemKind(f.ElemKind) {
			emitStreamSlice(b, f, prefix, dest, depth)
		}
	case KindMap:
		if supportedElemKind(f.ElemKind) {
			emitStreamMap(b, f, prefix, dest, depth)
		}
	case "file":
		// A file never arrives inside a JSON document.
		fmt.Fprintf(b, "%sif err := p.SkipValue(); err != nil {\n%s\treturn out, err\n%s}\n", prefix, prefix, prefix)
	}
}

// exportedKind is the scalar kind spelled the way jsonbind names its helpers.
func exportedKind(kind string) string {
	switch kind {
	case "int":
		return "Int"
	case "int64":
		return "Int64"
	case "bool":
		return "Bool"
	case "float64":
		return "Float64"
	case "string":
		return "String"
	}
	return ""
}

func parserMethod(kind string) string {
	switch kind {
	case "string":
		return "String"
	case "int":
		return "Int"
	case "int64":
		return "Int64"
	case "bool":
		return "Bool"
	case "float64":
		return "Float64"
	}
	return ""
}

func emitStreamSlice(b *bytes.Buffer, f FieldPlan, prefix, dest string, depth int) {
	elemType := f.ElemKind
	if f.ElemKind == KindStruct {
		elemType = f.TypeName
	}
	idx := fmt.Sprintf("i%d", depth)
	tmp := fmt.Sprintf("slice%d", depth)
	fmt.Fprintf(b, "%snull, err := p.ArrayStart()\n", prefix)
	fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid array\", err)\n%s}\n", prefix, prefix, f.Wire, prefix)
	fmt.Fprintf(b, "%sif !null {\n", prefix)
	inner := prefix + "\t"
	fmt.Fprintf(b, "%s%s := []%s{}\n", inner, tmp, elemType)
	fmt.Fprintf(b, "%sfor %s := 0; ; %s++ {\n", inner, idx, idx)
	loop := inner + "\t"
	fmt.Fprintf(b, "%smore, err := p.ArrayNext(%s)\n", loop, idx)
	fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid array\", err)\n%s}\n", loop, loop, f.Wire, loop)
	fmt.Fprintf(b, "%sif !more {\n%s\tbreak\n%s}\n", loop, loop, loop)
	// Sizing on the first element keeps an empty array allocation-free while
	// giving a populated one a single growth step in the common case.
	fmt.Fprintf(b, "%sif %s == 0 {\n%s\t%s = make([]%s, 0, 8)\n%s}\n", loop, idx, loop, tmp, elemType, loop)
	elem := FieldPlan{Name: f.Name, Wire: f.Wire, Kind: f.ElemKind, TypeName: f.TypeName}
	fmt.Fprintf(b, "%s{\n", loop)
	emitStreamAssignElem(b, elem, loop+"\t", "item", depth+1)
	fmt.Fprintf(b, "%s\t%s = append(%s, item)\n", loop, tmp, tmp)
	fmt.Fprintf(b, "%s}\n", loop)
	fmt.Fprintf(b, "%s}\n", inner)
	fmt.Fprintf(b, "%s%s = %s\n", inner, dest, tmp)
	fmt.Fprintf(b, "%s}\n", prefix)
}

func emitStreamMap(b *bytes.Buffer, f FieldPlan, prefix, dest string, depth int) {
	elemType := f.ElemKind
	if f.ElemKind == KindStruct {
		elemType = f.TypeName
	}
	idx := fmt.Sprintf("n%d", depth+1)
	tmp := fmt.Sprintf("mout%d", depth)
	fmt.Fprintf(b, "%snull, err := p.ObjectStart()\n", prefix)
	fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid map\", err)\n%s}\n", prefix, prefix, f.Wire, prefix)
	fmt.Fprintf(b, "%sif !null {\n", prefix)
	inner := prefix + "\t"
	fmt.Fprintf(b, "%s%s := map[string]%s{}\n", inner, tmp, elemType)
	fmt.Fprintf(b, "%sfor %s := 0; ; %s++ {\n", inner, idx, idx)
	loop := inner + "\t"
	fmt.Fprintf(b, "%smkey, mok, err := p.ObjectKey(%s)\n", loop, idx)
	fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid map\", err)\n%s}\n", loop, loop, f.Wire, loop)
	fmt.Fprintf(b, "%sif !mok {\n%s\tbreak\n%s}\n", loop, loop, loop)
	fmt.Fprintf(b, "%sname := string(mkey)\n", loop)
	elem := FieldPlan{Name: f.Name, Wire: f.Wire, Kind: f.ElemKind, TypeName: f.TypeName}
	fmt.Fprintf(b, "%s{\n", loop)
	emitStreamAssignElem(b, elem, loop+"\t", "item", depth+1)
	fmt.Fprintf(b, "%s\t%s[name] = item\n", loop, tmp)
	fmt.Fprintf(b, "%s}\n", loop)
	fmt.Fprintf(b, "%s}\n", inner)
	fmt.Fprintf(b, "%s%s = %s\n", inner, dest, tmp)
	fmt.Fprintf(b, "%s}\n", prefix)
}

// supportedElemKind reports the slice and map element kinds the planner can
// produce. Anything else emits no assignment at all, as the map-based emitter
// did, rather than code that would not compile.
func supportedElemKind(kind string) bool {
	switch kind {
	case "string", "int", "int64", "bool", "float64", KindStruct:
		return true
	}
	return false
}

// emitStreamAssignElem declares name and fills it with one element value.
func emitStreamAssignElem(b *bytes.Buffer, f FieldPlan, prefix, name string, depth int) {
	switch f.Kind {
	case KindStruct:
		fmt.Fprintf(b, "%s%s, err := decode%sJSON(p)\n", prefix, name, f.TypeName)
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, err\n%s}\n", prefix, prefix, prefix)
	default:
		fmt.Fprintf(b, "%s%s, err := p.%s()\n", prefix, name, parserMethod(f.Kind))
		fmt.Fprintf(b, "%sif err != nil {\n%s\treturn out, jsonbind.FieldError(%q, \"invalid %s\", err)\n%s}\n", prefix, prefix, f.Wire, f.Kind, prefix)
	}
}

func isDocumentField(f FieldPlan) bool {
	if f.Source == SourcePath || f.Source == SourceHeader || f.Source == SourceCookie || f.Source == SourceMethod || f.Source == SourceQuery {
		return false
	}
	if f.Kind == "file" {
		return false
	}
	return f.Source == SourceInput || f.Source == SourcePayload
}

func emitAssignFromRaw(b *bytes.Buffer, f FieldPlan, types map[string]TypePlan, rawVar, prefix, dest string, returnOut bool) {
	ret := "return out, "
	if !returnOut {
		ret = "return "
	}
	switch f.Kind {
	case "string":
		fmt.Fprintf(b, "%sv, err := jsonbind.DecodeJSONString(%s)\n", prefix, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%sjsonbind.FieldError(%q, \"invalid string\", err)\n%s}\n", prefix, prefix, ret, f.Wire, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case "int":
		fmt.Fprintf(b, "%sv, err := jsonbind.DecodeJSONInt(%s)\n", prefix, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%sjsonbind.FieldError(%q, \"invalid int\", err)\n%s}\n", prefix, prefix, ret, f.Wire, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case "int64":
		fmt.Fprintf(b, "%sv, err := jsonbind.DecodeJSONInt64(%s)\n", prefix, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%sjsonbind.FieldError(%q, \"invalid int64\", err)\n%s}\n", prefix, prefix, ret, f.Wire, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case "bool":
		fmt.Fprintf(b, "%sv, err := jsonbind.DecodeJSONBool(%s)\n", prefix, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%sjsonbind.FieldError(%q, \"invalid bool\", err)\n%s}\n", prefix, prefix, ret, f.Wire, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case "float64":
		fmt.Fprintf(b, "%sv, err := jsonbind.DecodeJSONFloat64(%s)\n", prefix, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%sjsonbind.FieldError(%q, \"invalid float64\", err)\n%s}\n", prefix, prefix, ret, f.Wire, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case KindStruct:
		fmt.Fprintf(b, "%sv, err := decode%sBytes(%s)\n", prefix, f.TypeName, rawVar)
		fmt.Fprintf(b, "%sif err != nil {\n%s\t%serr\n%s}\n", prefix, prefix, ret, prefix)
		fmt.Fprintf(b, "%s%s = v\n", prefix, dest)
	case KindSlice:
		emitAssignSliceFromRaw(b, f, rawVar, prefix, dest, ret)
	case KindMap:
		emitAssignMapFromRaw(b, f, rawVar, prefix, dest, ret)
	case "file":
		// file cannot be decoded from JSON object fields
	}
}

