// Package codegen emits reflection-free configbind apply, flag, and env key tables.
package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/shibukawa/tinybind-go/cliparser"
	"github.com/shibukawa/tinybind-go/minitoml/codegen"
)

// Spec is a Bind-style struct and prefix discovered in one Go package.
type Spec struct {
	PackagePath string
	TypeName    string
	Prefix      string
	SubCommand  bool
	Name        string
	Help        string
	// Doc is the struct's godoc text. Bind specs render it above the scaffold
	// table; subcommand specs fall back to it when Help is empty.
	Doc    string
	Fields []Field
}

// Field and FieldKind re-export for callers.
type (
	Field     = codegen.Field
	FieldKind = codegen.FieldKind
)

const (
	FieldString      = codegen.FieldString
	FieldBool        = codegen.FieldBool
	FieldInt         = codegen.FieldInt
	FieldDuration    = codegen.FieldDuration
	FieldStringSlice = codegen.FieldStringSlice
	FieldStruct      = codegen.FieldStruct
	FieldStructSlice = codegen.FieldStructSlice
)

// Generate emits package source that registers one Definition for each Spec.
func Generate(packageName string, specs []Spec) ([]byte, error) {
	return GenerateGroup(packageName, specs, 0)
}

// GenerateGroup generates one subset of a package's specs. indexOffset is the
// position of specs[0] within the package's full spec list; it keeps generated
// identifiers unique when a package is emitted as several files.
func GenerateGroup(packageName string, specs []Spec, indexOffset int) ([]byte, error) {
	if packageName == "" {
		return nil, fmt.Errorf("configbind/codegen: package name required")
	}
	if len(specs) == 0 {
		return nil, fmt.Errorf("configbind/codegen: no specs")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by configbind/codegen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	b.WriteString("import (\n")
	b.WriteString("\t\"fmt\"\n")
	if specsNeedStrconv(specs) {
		b.WriteString("\t\"strconv\"\n")
	}
	if specsNeedTime(specs) {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString("\n")
	b.WriteString("\t\"github.com/shibukawa/tinybind-go/cliparser\"\n")
	b.WriteString("\t\"github.com/shibukawa/tinybind-go/configbind\"\n")
	b.WriteString(")\n\n")

	b.WriteString("func init() {\n")
	for i, s := range specs {
		fmt.Fprintf(&b, "\tregister%sDefinition%d()\n", s.TypeName, indexOffset+i)
	}
	b.WriteString("}\n\n")

	// run lets dependon conditions be checked against the keys generated here. A
	// parent bound in another package is invisible and passes.
	knownFalsy, err := knownFalsyChoices(specs)
	if err != nil {
		return nil, fmt.Errorf("configbind/codegen: %w", err)
	}
	run := runScope{
		kinds:    knownFieldKinds(specs),
		falsy:    knownFalsy,
		enums:    knownEnumChoices(specs),
		intTypes: knownIntTypes(specs),
	}
	for i, s := range specs {
		if s.PackagePath == "" {
			s.PackagePath = packageName
		}
		registerName := fmt.Sprintf("register%sDefinition%d", s.TypeName, indexOffset+i)
		var genErr error
		if s.SubCommand {
			genErr = emitSubCommandType(&b, s, registerName)
		} else {
			genErr = emitType(&b, s, registerName, run)
		}
		if genErr != nil {
			return nil, genErr
		}
	}

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("configbind/codegen: format: %w\n%s", err, b.String())
	}
	return formatted, nil
}

func specsNeedStrconv(specs []Spec) bool {
	var fieldsNeedStrconv func([]Field) bool
	fieldsNeedStrconv = func(fields []Field) bool {
		for _, field := range fields {
			if field.Kind == FieldBool || field.Kind == FieldInt ||
				((field.Kind == FieldStruct || field.Kind == FieldStructSlice) && fieldsNeedStrconv(field.Nested)) {
				return true
			}
		}
		return false
	}
	for _, spec := range specs {
		if fieldsNeedStrconv(spec.Fields) {
			return true
		}
	}
	return false
}

func specsNeedTime(specs []Spec) bool {
	var fieldsNeedTime func([]Field) bool
	fieldsNeedTime = func(fields []Field) bool {
		for _, field := range fields {
			if field.Kind == FieldDuration ||
				(field.Kind == FieldStruct && fieldsNeedTime(field.Nested)) {
				return true
			}
		}
		return false
	}
	for _, spec := range specs {
		if fieldsNeedTime(spec.Fields) {
			return true
		}
	}
	return false
}

// runScope is what one spec can see of the whole generation run: a dependon
// parent may live in another spec of the same run, so its kind, falsy choice,
// enum, and integer width are all resolved run-wide rather than per spec.
type runScope struct {
	kinds    map[string]FieldKind
	falsy    map[string]string
	enums    map[string]string
	intTypes map[string]string
}

func emitType(b *bytes.Buffer, s Spec, registerName string, run runScope) error {
	if s.TypeName == "" || s.Prefix == "" {
		return fmt.Errorf("configbind/codegen: TypeName and Prefix required")
	}
	for _, field := range flattenFields("", s.Fields) {
		if field.Field.Arg != "" {
			return fmt.Errorf("configbind/codegen: Bind field %s cannot use arg tag", field.Field.GoName)
		}
	}
	if err := checkTableArrayFields(s.Fields); err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	if err := checkStructFieldTags("", s.Fields); err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	keys := collectKeys(s.Prefix, s.Fields)
	defaults := collectDefaults(s.Prefix, s.Fields)
	falsy, err := collectFalsy(s.Prefix, s.Fields)
	if err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	dependsOn, err := collectDependsOn(s.Prefix, s.Fields, run.kinds, run.falsy, run.enums, run.intTypes)
	if err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	secrets, err := collectSecrets(s.Prefix, s.Fields)
	if err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	summary, err := collectSummary(s.Prefix, s.Fields)
	if err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}
	flagMetas := collectFlagMetas(s.Prefix, s.Fields)
	if _, err := cliparser.BuildDefs(flagMetas); err != nil {
		return fmt.Errorf("configbind/codegen: %s: %w", s.TypeName, err)
	}

	typeIdentity := s.PackagePath + "." + s.TypeName
	applyName := "apply" + strings.TrimPrefix(registerName, "register")
	fmt.Fprintf(b, "func %s() {\n", registerName)
	b.WriteString("\tconfigbind.Register[")
	b.WriteString(s.TypeName)
	b.WriteString("](configbind.Definition{\n")
	fmt.Fprintf(b, "\t\tTypeName: %s,\n", strconv.Quote(typeIdentity))
	fmt.Fprintf(b, "\t\tPrefix: %s,\n", strconv.Quote(s.Prefix))
	if s.Doc != "" {
		fmt.Fprintf(b, "\t\tDoc: %s,\n", strconv.Quote(s.Doc))
	}
	b.WriteString("\t\tKnownKeys: []string{\n")
	for _, k := range keys {
		fmt.Fprintf(b, "\t\t\t%s,\n", strconv.Quote(k))
	}
	b.WriteString("\t\t},\n")
	if len(defaults) > 0 {
		b.WriteString("\t\tDefaults: map[string]string{\n")
		// stable order
		for _, k := range keys {
			if v, ok := defaults[k]; ok {
				fmt.Fprintf(b, "\t\t\t%s: %s,\n", strconv.Quote(k), strconv.Quote(v))
			}
		}
		b.WriteString("\t\t},\n")
	}
	if len(dependsOn) > 0 {
		b.WriteString("\t\tDependsOn: map[string][]configbind.Dependency{\n")
		for _, k := range keys {
			parents, ok := dependsOn[k]
			if !ok {
				continue
			}
			rendered := make([]string, 0, len(parents))
			for _, condition := range parents {
				rendered = append(rendered, renderDependency(condition))
			}
			fmt.Fprintf(b, "\t\t\t%s: {%s},\n", strconv.Quote(k), strings.Join(rendered, ", "))
		}
		b.WriteString("\t\t},\n")
	}
	if len(falsy) > 0 {
		b.WriteString("\t\tFalsy: map[string]string{\n")
		for _, k := range keys {
			if value, ok := falsy[k]; ok {
				fmt.Fprintf(b, "\t\t\t%s: %s,\n", strconv.Quote(k), strconv.Quote(value))
			}
		}
		b.WriteString("\t\t},\n")
	}
	if len(secrets) > 0 {
		b.WriteString("\t\tSecrets: map[string]string{\n")
		for _, secret := range secrets {
			fmt.Fprintf(b, "\t\t\t%s: %s,\n", strconv.Quote(secret.Key), strconv.Quote(secret.Mode))
		}
		b.WriteString("\t\t},\n")
	}
	if len(summary) > 0 {
		b.WriteString("\t\tSummary: map[string]string{\n")
		for _, rating := range summary {
			fmt.Fprintf(b, "\t\t\t%s: %s,\n", strconv.Quote(rating.Key), strconv.Quote(rating.Mode))
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t\tFlagMetas: []cliparser.FieldMeta{\n")
	for _, m := range flagMetas {
		fmt.Fprintf(b, "\t\t\t{Prefix: %s, Key: %s", strconv.Quote(m.Prefix), strconv.Quote(m.Key))
		if m.Opt != "" {
			fmt.Fprintf(b, ", Opt: %s", strconv.Quote(m.Opt))
		}
		if m.Env != "" {
			fmt.Fprintf(b, ", Env: %s", strconv.Quote(m.Env))
		}
		if m.Help != "" {
			fmt.Fprintf(b, ", Help: %s", strconv.Quote(m.Help))
		}
		switch m.Kind {
		case cliparser.KindBool:
			b.WriteString(", Kind: cliparser.KindBool")
		case cliparser.KindArray:
			b.WriteString(", Kind: cliparser.KindArray")
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t\t},\n")
	fmt.Fprintf(b, "\t\tApply: %s,\n", applyName)
	b.WriteString("\t\tScaffold: []configbind.ScaffoldField{\n")
	writeScaffoldFields(b, flattenScaffoldFields("", s.Fields))
	b.WriteString("\t\t},\n")
	b.WriteString("\t})\n")
	b.WriteString("}\n\n")

	// Apply function
	fmt.Fprintf(b, "func %s(dst any, o *configbind.Overlay) error {\n", applyName)
	fmt.Fprintf(b, "\tp, ok := dst.(*%s)\n", s.TypeName)
	b.WriteString("\tif !ok || p == nil {\n")
	fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"configbind: apply %s: bad destination\")\n", s.TypeName)
	b.WriteString("\t}\n")
	if err := emitApplyFields(b, applyScope{src: "o"}, "p", s.Prefix, s.Fields); err != nil {
		return err
	}
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n\n")
	return nil
}

func emitSubCommandType(b *bytes.Buffer, s Spec, registerName string) error {
	if s.Help == "" {
		s.Help = s.Doc
	}
	if s.TypeName == "" || s.Name == "" || s.Help == "" {
		return fmt.Errorf("configbind/codegen: subcommand TypeName, Name, and Help required")
	}
	if strings.ContainsAny(s.Name, " \t\r\n") || strings.HasPrefix(s.Name, "-") {
		return fmt.Errorf("configbind/codegen: invalid subcommand name %q", s.Name)
	}
	if err := rejectTableArrays(s.Fields); err != nil {
		return fmt.Errorf("configbind/codegen: subcommand %s: %w", s.Name, err)
	}
	for _, field := range flattenFields("", s.Fields) {
		for _, tag := range []struct {
			name string
			set  bool
		}{
			// Parents and Secret include what a struct above the field
			// declared, so a tag written there is caught here too.
			{"dependon", len(field.Parents) > 0},
			{"falsy", field.Field.Falsy != ""},
			{"secret", field.Secret != ""},
			// A subcommand field never reaches provenance, so rating it as detail
			// rates it for an output it does not appear in.
			{"summary", field.Summary != ""},
		} {
			if tag.set {
				return fmt.Errorf("configbind/codegen: subcommand %s: field %s cannot use %s; subcommand fields are not overlay-backed",
					s.Name, field.Field.GoName, tag.name)
			}
		}
	}
	flagMetas := collectFlagMetas("", s.Fields)
	if _, err := cliparser.BuildDefs(flagMetas); err != nil {
		return fmt.Errorf("configbind/codegen: subcommand %s: %w", s.Name, err)
	}
	positionals, err := collectPositionals(s.Fields)
	if err != nil {
		return fmt.Errorf("configbind/codegen: subcommand %s: %w", s.Name, err)
	}
	defaults := collectDefaults("", s.Fields)
	keys := collectKeys("", s.Fields)
	typeIdentity := s.PackagePath + "." + s.TypeName
	applyName := "apply" + strings.TrimPrefix(registerName, "register")

	fmt.Fprintf(b, "func %s() {\n", registerName)
	fmt.Fprintf(b, "\tconfigbind.RegisterSubCommand[%s](configbind.SubCommandDefinition{\n", s.TypeName)
	fmt.Fprintf(b, "\t\tTypeName: %s,\n", strconv.Quote(typeIdentity))
	fmt.Fprintf(b, "\t\tName: %s,\n", strconv.Quote(s.Name))
	fmt.Fprintf(b, "\t\tHelp: %s,\n", strconv.Quote(s.Help))
	if len(defaults) > 0 {
		b.WriteString("\t\tDefaults: map[string]string{\n")
		for _, key := range keys {
			if value, ok := defaults[key]; ok {
				fmt.Fprintf(b, "\t\t\t%s: %s,\n", strconv.Quote(key), strconv.Quote(value))
			}
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t\tFlagMetas: []cliparser.FieldMeta{\n")
	for _, meta := range flagMetas {
		fmt.Fprintf(b, "\t\t\t{Key: %s, Env: \"-\"", strconv.Quote(meta.Key))
		if meta.Opt != "" {
			fmt.Fprintf(b, ", Opt: %s", strconv.Quote(meta.Opt))
		}
		if meta.Help != "" {
			fmt.Fprintf(b, ", Help: %s", strconv.Quote(meta.Help))
		}
		switch meta.Kind {
		case cliparser.KindBool:
			b.WriteString(", Kind: cliparser.KindBool")
		case cliparser.KindArray:
			b.WriteString(", Kind: cliparser.KindArray")
		}
		b.WriteString("},\n")
	}
	b.WriteString("\t\t},\n")
	if len(positionals) > 0 {
		b.WriteString("\t\tPositionals: []configbind.Positional{\n")
		for _, positional := range positionals {
			fmt.Fprintf(b, "\t\t\t{ConfigKey: %s, Name: %s, Role: %s",
				strconv.Quote(positional.Key), strconv.Quote(positional.Key), positionalRoleName(positional.Field.Arg))
			if positional.Field.Help != "" {
				fmt.Fprintf(b, ", Help: %s", strconv.Quote(positional.Field.Help))
			}
			b.WriteString("},\n")
		}
		b.WriteString("\t\t},\n")
	}
	fmt.Fprintf(b, "\t\tApply: %s,\n", applyName)
	b.WriteString("\t})\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func %s(dst any, o *configbind.Overlay) error {\n", applyName)
	fmt.Fprintf(b, "\tp, ok := dst.(*%s)\n", s.TypeName)
	b.WriteString("\tif !ok || p == nil {\n")
	fmt.Fprintf(b, "\t\treturn fmt.Errorf(\"configbind: apply %s: bad destination\")\n", s.TypeName)
	b.WriteString("\t}\n")
	if err := emitApplyFields(b, applyScope{src: "o"}, "p", "", s.Fields); err != nil {
		return err
	}
	b.WriteString("\treturn nil\n")
	b.WriteString("}\n\n")
	return nil
}

type scaffoldCodegenField struct {
	Key   string
	Field Field
	// Nested holds the element fields of an array of tables, keyed relative to Key.
	Nested []scaffoldCodegenField
	// Parents are the dependon conditions this key answers to: its own tag plus
	// every tag declared on a struct above it.
	Parents []dependency
	// Secret is the disclosure mode in force here, from this field's own tag or
	// the nearest struct above it that declared one.
	Secret string
	// Summary is the detail rating in force here, resolved like Secret. The emit
	// path reads collectSummary instead; this exists so a tag inherited from a
	// struct is still visible to the subcommand rejection.
	Summary string
}

// dependency is one parsed dependon tag with its parent key already resolved to
// an absolute one. It mirrors configbind.Dependency, which the generated code
// names; the two are kept apart so codegen does not import the runtime package.
type dependency struct {
	Key    string
	Op     string
	Values []string
	// Owner is the Go field the tag was written on, which is what a rejection has
	// to name: an inherited condition is reported against the struct that declared
	// it, not against the leaf that inherited it.
	Owner string
}

// Operators a dependon tag may carry. They mirror the configbind constants of
// the same value, which this package emits as text rather than importing.
const (
	dependOpEqual    = "="
	dependOpNotEqual = "!="
)

// parseDependOn splits one dependon tag into a condition and resolves its parent
// key against prefix. The second result reports that a tag was written at all,
// not that it is valid: an unusable one is returned for collectDependsOn to
// reject by name, because a tag accepted and dropped here is the defect
// requirement:struct-tag-placement-totality exists to prevent.
//
// The operator is the first "=" in the tag, so a value may itself contain one; a
// value may not contain a comma, which separates the alternatives, exactly as in
// an enum tag. A comma with no operator before it stays in the key, where
// collectDependsOn rejects it as the parent list it has always been.
func parseDependOn(prefix, tag string) (dependency, bool) {
	tag = strings.TrimSpace(tag)
	if tag == "" {
		return dependency{}, false
	}
	keyPart, valuePart := tag, ""
	op := ""
	if at := strings.Index(tag, "="); at >= 0 {
		op = dependOpEqual
		keyPart, valuePart = tag[:at], tag[at+1:]
		if strings.HasSuffix(keyPart, "!") {
			op = dependOpNotEqual
			keyPart = strings.TrimSuffix(keyPart, "!")
		}
	}
	condition := dependency{Key: resolveParentKey(prefix, keyPart), Op: op}
	if op == "" {
		return condition, true
	}
	for _, value := range strings.Split(valuePart, ",") {
		condition.Values = append(condition.Values, strings.TrimSpace(value))
	}
	return condition, true
}

// flattenFields returns the leaf fields reachable by a single config key.
// Arrays of tables are skipped: their element fields are addressed per element,
// not by one stable key, so they have no flag, env, or default of their own.
//
// A dependon, secret, or summary tag on a nested struct covers the whole subtree,
// so the walk carries all three down; a leaf's own dependon adds to the inherited
// parents rather than replacing them, because both conditions have to hold for the
// key to be worth printing. secret and summary each state one mode, so the nearest
// one in force simply wins.
func flattenFields(prefix string, fields []Field) []scaffoldCodegenField {
	return flattenInheriting(prefix, fields, nil, "", "")
}

func flattenInheriting(prefix string, fields []Field, parents []dependency, secret, summary string) []scaffoldCodegenField {
	var result []scaffoldCodegenField
	for _, field := range fields {
		key := joinKey(prefix, field.Key)
		fieldParents := parents
		if condition, ok := parseDependOn(prefix, field.DependsOn); ok {
			condition.Owner = field.GoName
			fieldParents = append(append([]dependency(nil), parents...), condition)
		}
		fieldSecret := secret
		if field.Secret != "" {
			fieldSecret = field.Secret
		}
		fieldSummary := summary
		if field.Summary != "" {
			fieldSummary = field.Summary
		}
		switch field.Kind {
		case FieldStruct:
			result = append(result, flattenInheriting(key, field.Nested, fieldParents, fieldSecret, fieldSummary)...)
		case FieldStructSlice:
			// The array itself is one stable key, so it carries its own dependon,
			// secret, and summary. Its elements are addressed per element and are
			// collected by the mode walks instead.
			result = append(result, scaffoldCodegenField{
				Key:     key,
				Field:   field,
				Parents: fieldParents,
				Secret:  fieldSecret,
				Summary: fieldSummary,
			})
		default:
			result = append(result, scaffoldCodegenField{
				Key:     key,
				Field:   field,
				Parents: fieldParents,
				Secret:  fieldSecret,
				Summary: fieldSummary,
			})
		}
	}
	return result
}

// resolveParentKey turns one dependon tag into an absolute config key. A
// leading dot makes it relative to the struct the tag is written in, which is
// what lets one shared struct type name a sibling under every prefix it is
// embedded at; anything else is already absolute.
func resolveParentKey(prefix, tag string) string {
	tag = strings.TrimSpace(tag)
	if tag == "" {
		return ""
	}
	if rest, ok := strings.CutPrefix(tag, "."); ok {
		return joinKey(prefix, strings.TrimSpace(rest))
	}
	return tag
}

// flattenScaffoldFields is flattenFields plus one entry per array of tables,
// which the scaffold renders as its own [[key]] block.
func flattenScaffoldFields(prefix string, fields []Field) []scaffoldCodegenField {
	var result []scaffoldCodegenField
	for _, field := range fields {
		key := joinKey(prefix, field.Key)
		switch field.Kind {
		case FieldStruct:
			result = append(result, flattenScaffoldFields(key, field.Nested)...)
		case FieldStructSlice:
			result = append(result, scaffoldCodegenField{
				Key:    key,
				Field:  field,
				Nested: flattenScaffoldFields("", field.Nested),
			})
		default:
			result = append(result, scaffoldCodegenField{Key: key, Field: field})
		}
	}
	return result
}

func writeScaffoldFields(b *bytes.Buffer, fields []scaffoldCodegenField) {
	for _, scaffoldField := range fields {
		f := scaffoldField.Field
		fmt.Fprintf(b, "\t\t{Key: %s, Kind: %s", strconv.Quote(scaffoldField.Key), scaffoldKindName(f.Kind))
		if f.Default != "" {
			fmt.Fprintf(b, ", Default: %s", strconv.Quote(f.Default))
		}
		if f.Opt != "" {
			fmt.Fprintf(b, ", Opt: %s", strconv.Quote(f.Opt))
		}
		if f.Env != "" {
			fmt.Fprintf(b, ", Env: %s", strconv.Quote(f.Env))
		}
		if f.Help != "" {
			fmt.Fprintf(b, ", Help: %s", strconv.Quote(f.Help))
		}
		if len(scaffoldField.Nested) > 0 {
			b.WriteString(", Nested: []configbind.ScaffoldField{\n")
			writeScaffoldFields(b, scaffoldField.Nested)
			b.WriteString("}")
		}
		b.WriteString("},\n")
	}
}

// checkTableArrayFields rejects tags that cannot reach an array-of-tables
// element: it has no flag, env var, or single config key of its own.
func checkTableArrayFields(fields []Field) error {
	for _, field := range fields {
		switch field.Kind {
		case FieldStruct:
			if err := checkTableArrayFields(field.Nested); err != nil {
				return err
			}
		case FieldStructSlice:
			if field.Opt != "" || field.Env != "" {
				return fmt.Errorf("field %s: an array of tables has no flag or env form", field.GoName)
			}
			if err := checkElementFields(field.GoName, field.Nested); err != nil {
				return err
			}
		}
	}
	return nil
}

// rejectTableArrays refuses arrays of tables where only CLI arguments arrive:
// a subcommand is never fed from a config file.
func rejectTableArrays(fields []Field) error {
	for _, field := range fields {
		switch field.Kind {
		case FieldStruct:
			if err := rejectTableArrays(field.Nested); err != nil {
				return err
			}
		case FieldStructSlice:
			return fmt.Errorf("field %s: a subcommand cannot take an array of tables", field.GoName)
		}
	}
	return nil
}

// checkStructFieldTags rejects the tags a struct field cannot carry.
//
// Every tag has an outcome here, because the tags that reached this walk without
// one were accepted and dropped: a default on a nested struct generated nothing
// and reported nothing. dependon and secret describe a whole subtree and are
// propagated to its leaves. falsy and enum each name a value or a set of them,
// which neither a struct nor an array has. default, opt, env, and arg each
// address one scalar key, so they have nowhere to land on either.
//
// help is the exception: requirement:godoc-help-precedence backfills help tags
// into source from godoc, including onto struct fields, so rejecting it here
// would fail the generation run that wrote it.
func checkStructFieldTags(prefix string, fields []Field) error {
	for _, field := range fields {
		key := joinKey(prefix, field.Key)
		switch field.Kind {
		case FieldStruct:
			if err := checkScalarOnlyTags(field, "the nested struct "+key); err != nil {
				return err
			}
			if err := checkValueSetTags(field, "the nested struct "+key); err != nil {
				return err
			}
			if err := checkStructFieldTags(key, field.Nested); err != nil {
				return err
			}
		case FieldStructSlice:
			if err := checkScalarOnlyTags(field, "the array of tables "+key); err != nil {
				return err
			}
			// dependon and secret stay: the array itself owns one stable key, so a
			// parent can hide it whole and a disclosure mode can cover its elements.
			// Only the tags that name values have none to name.
			if err := checkValueSetTags(field, "the array of tables "+key); err != nil {
				return err
			}
		}
	}
	return nil
}

// checkValueSetTags rejects the tags that name a value of the field they sit on.
// A struct and an array hold no value of their own, so neither an off choice nor
// an allowlist has anything to be compared against.
func checkValueSetTags(field Field, subject string) error {
	for _, tag := range []struct {
		name string
		set  bool
		why  string
	}{
		{"falsy", field.Falsy != "", "falsy names one value"},
		{"enum", field.Enum != "", "an allowlist constrains one value"},
	} {
		if tag.set {
			return fmt.Errorf("field %s: %s applies to a leaf field, not to %s; %s", field.GoName, tag.name, subject, tag.why)
		}
	}
	return nil
}

// checkScalarOnlyTags rejects the tags that address exactly one scalar key.
func checkScalarOnlyTags(field Field, subject string) error {
	for _, tag := range []struct {
		name string
		set  bool
		why  string
	}{
		{"default", field.Default != "", "a default is one parsed value"},
		{"opt", field.Opt != "", "a CLI flag carries one value"},
		{"env", field.Env != "", "an environment variable carries one value"},
		{"arg", field.Arg != "", "a positional argument carries one value"},
	} {
		if tag.set {
			return fmt.Errorf("field %s: %s applies to a leaf field, not to %s; %s", field.GoName, tag.name, subject, tag.why)
		}
	}
	return nil
}

// checkElementFields rejects the tags an array-of-tables element field cannot
// carry. secret is not among them: an element value needs redaction as much as
// any other, and it is resolved by the element's path under the array key, which
// is stable even though the element's own key carries a runtime index.
func checkElementFields(owner string, fields []Field) error {
	for _, field := range fields {
		if field.Opt != "" || field.Env != "" || field.Arg != "" {
			return fmt.Errorf("field %s.%s: fields of an array-of-tables element have no flag, env, or positional form", owner, field.GoName)
		}
		// An element field has no stable config key, so nothing can name it as a
		// dependon parent and nothing can look it up to hide or fill it in. An enum
		// is rejected for the same reason a dependon parent cannot be one: the
		// allowlist would have no key to be checked against.
		if field.DependsOn != "" || field.Falsy != "" || field.Enum != "" {
			return fmt.Errorf("field %s.%s: fields of an array-of-tables element have no provenance key for dependon, falsy, or enum", owner, field.GoName)
		}
		if err := checkElementFields(owner+"."+field.GoName, field.Nested); err != nil {
			return err
		}
	}
	return nil
}

func collectPositionals(fields []Field) ([]scaffoldCodegenField, error) {
	var result []scaffoldCodegenField
	optionalSeen := false
	restSeen := false
	for _, field := range fields {
		if field.Kind == FieldStruct || field.Kind == FieldStructSlice {
			if field.Arg != "" {
				return nil, fmt.Errorf("field %s: nested struct cannot be positional", field.GoName)
			}
			nested, err := collectPositionals(field.Nested)
			if err != nil {
				return nil, err
			}
			if len(nested) > 0 {
				return nil, fmt.Errorf("field %s: nested positional fields are not supported", field.GoName)
			}
			continue
		}
		if field.Arg == "" {
			continue
		}
		switch field.Arg {
		case "required":
			if optionalSeen || restSeen {
				return nil, fmt.Errorf("required positional %s must precede optional and rest arguments", field.Key)
			}
			if field.Kind == FieldStringSlice {
				return nil, fmt.Errorf("required positional %s must be a scalar", field.Key)
			}
		case "optional":
			if restSeen {
				return nil, fmt.Errorf("optional positional %s must precede the rest argument", field.Key)
			}
			if field.Kind == FieldStringSlice {
				return nil, fmt.Errorf("optional positional %s must be a scalar", field.Key)
			}
			optionalSeen = true
		case "*":
			if restSeen || field.Kind != FieldStringSlice {
				return nil, fmt.Errorf("rest positional %s must be a unique []string field", field.Key)
			}
			restSeen = true
		default:
			return nil, fmt.Errorf("field %s has invalid arg tag %q", field.GoName, field.Arg)
		}
		result = append(result, scaffoldCodegenField{Key: field.Key, Field: field})
	}
	if restSeen && result[len(result)-1].Field.Arg != "*" {
		return nil, fmt.Errorf("rest positional must be last")
	}
	return result, nil
}

func positionalRoleName(role string) string {
	switch role {
	case "required":
		return "configbind.PositionalRequired"
	case "optional":
		return "configbind.PositionalOptional"
	default:
		return "configbind.PositionalRest"
	}
}

func scaffoldKindName(kind FieldKind) string {
	switch kind {
	case FieldString:
		return "configbind.ScaffoldString"
	case FieldBool:
		return "configbind.ScaffoldBool"
	case FieldInt:
		return "configbind.ScaffoldInt"
	case FieldDuration:
		return "configbind.ScaffoldDuration"
	case FieldStringSlice:
		return "configbind.ScaffoldStringSlice"
	case FieldStructSlice:
		return "configbind.ScaffoldTableArray"
	default:
		return "configbind.ScaffoldString"
	}
}

// applyScope is where one group of fields reads from: the Go expression holding
// their overlay (the whole overlay at the top level, or one array-of-tables
// element inside a loop), the key path diagnostics name them by, and the
// nesting depth that keeps loop variables apart.
type applyScope struct {
	src        string
	diagPrefix string
	// diagIndexArgs names the loop variables that fill the [%d] verbs diagPrefix
	// carries, in the order they appear. An element's only identifier is its
	// position, so an error inside one has to name it.
	diagIndexArgs []string
	depth         int
}

// diagKey returns the key as a Go format string; it holds a [%d] verb per array
// of tables enclosing this scope.
func (s applyScope) diagKey(key string) string {
	return joinKey(s.diagPrefix, key)
}

// diagArgs returns the argument list that precedes any later verb, ready to
// splice into an emitted fmt.Errorf call.
func (s applyScope) diagArgs() string {
	if len(s.diagIndexArgs) == 0 {
		return ""
	}
	return ", " + strings.Join(s.diagIndexArgs, ", ")
}

// doubledDiagArgs feeds a message that spells the key twice, so each occurrence
// gets its own copy of the index arguments.
func doubledDiagArgs(s applyScope) string {
	if len(s.diagIndexArgs) == 0 {
		return ""
	}
	both := append(append([]string(nil), s.diagIndexArgs...), s.diagIndexArgs...)
	return ", " + strings.Join(both, ", ")
}

// emitApplyFields writes the field assignments for one struct.
func emitApplyFields(b *bytes.Buffer, scope applyScope, recv, prefix string, fields []Field) error {
	src := scope.src
	for _, f := range fields {
		full := joinKey(prefix, f.Key)
		access := recv + "." + f.GoName
		switch f.Kind {
		case FieldString:
			fmt.Fprintf(b, "\tif v, ok := %s.GetString(%q); ok {\n", src, full)
			fmt.Fprintf(b, "\t\t%s = v\n", access)
			if f.Default != "" {
				b.WriteString("\t} else {\n")
				fmt.Fprintf(b, "\t\t%s = %s\n", access, strconv.Quote(f.Default))
				b.WriteString("\t}\n")
			} else {
				b.WriteString("\t}\n")
			}
		case FieldBool:
			fmt.Fprintf(b, "\tif v, ok := %s.GetString(%q); ok {\n", src, full)
			b.WriteString("\t\tbb, err := strconv.ParseBool(v)\n")
			b.WriteString("\t\tif err != nil {\n")
			fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"configbind: %s: %%w\"%s, err)\n", scope.diagKey(full), scope.diagArgs())
			b.WriteString("\t\t}\n")
			fmt.Fprintf(b, "\t\t%s = bb\n", access)
			if f.Default != "" {
				value, err := strconv.ParseBool(f.Default)
				if err != nil {
					return fmt.Errorf("invalid bool default %q for %s", f.Default, f.GoName)
				}
				b.WriteString("\t} else {\n")
				fmt.Fprintf(b, "\t\t%s = %v\n", access, value)
				b.WriteString("\t}\n")
			} else {
				b.WriteString("\t}\n")
			}
		case FieldInt:
			// Parsing at the field's own width keeps an int64 field from being
			// narrowed to int, and turns an out-of-range value into an error
			// instead of a wrapped one.
			spec, err := codegen.IntFieldSpecOf(f.GoType)
			if err != nil {
				return fmt.Errorf("field %s: %w", f.GoName, err)
			}
			parse := "strconv.ParseInt"
			if !spec.Signed {
				parse = "strconv.ParseUint"
			}
			fmt.Fprintf(b, "\tif v, ok := %s.GetString(%q); ok {\n", src, full)
			fmt.Fprintf(b, "\t\tn, err := %s(v, 10, %d)\n", parse, spec.BitSize)
			b.WriteString("\t\tif err != nil {\n")
			fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"configbind: %s: %%w\"%s, err)\n", scope.diagKey(full), scope.diagArgs())
			b.WriteString("\t\t}\n")
			fmt.Fprintf(b, "\t\t%s = %s(n)\n", access, spec.Name)
			if f.Default != "" {
				literal, err := spec.ParseLiteral(f.Default)
				if err != nil {
					return fmt.Errorf("invalid %s default %q for %s", spec.Name, f.Default, f.GoName)
				}
				b.WriteString("\t} else {\n")
				fmt.Fprintf(b, "\t\t%s = %s\n", access, literal)
				b.WriteString("\t}\n")
			} else {
				b.WriteString("\t}\n")
			}
		case FieldDuration:
			fmt.Fprintf(b, "\tif v, ok := %s.GetString(%q); ok {\n", src, full)
			b.WriteString("\t\td, err := time.ParseDuration(v)\n")
			b.WriteString("\t\tif err != nil {\n")
			fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"configbind: %s: %%w\"%s, err)\n", scope.diagKey(full), scope.diagArgs())
			b.WriteString("\t\t}\n")
			fmt.Fprintf(b, "\t\t%s = d\n", access)
			if f.Default != "" {
				value, err := time.ParseDuration(f.Default)
				if err != nil {
					return fmt.Errorf("invalid duration default %q for %s", f.Default, f.GoName)
				}
				b.WriteString("\t} else {\n")
				fmt.Fprintf(b, "\t\t%s = %d // %s\n", access, int64(value), value)
				b.WriteString("\t}\n")
			} else {
				b.WriteString("\t}\n")
			}
		case FieldStringSlice:
			fmt.Fprintf(b, "\tif v, ok := %s.GetMulti(%q); ok {\n", src, full)
			fmt.Fprintf(b, "\t\t%s = v\n", access)
			b.WriteString("\t}\n")
		case FieldStruct:
			if err := emitApplyFields(b, scope, access, full, f.Nested); err != nil {
				return err
			}
		case FieldStructSlice:
			if err := emitApplyStructSlice(b, scope, access, full, f); err != nil {
				return err
			}
		default:
			return fmt.Errorf("unsupported field kind for %s", f.GoName)
		}
	}
	return nil
}

// emitApplyStructSlice expands one array of tables into a loop over its element
// overlays. Element keys are relative to the array key, so the element fields
// are emitted with an empty prefix.
func emitApplyStructSlice(b *bytes.Buffer, scope applyScope, access, full string, f Field) error {
	if f.ElemType == "" {
		return fmt.Errorf("field %s needs ElemType for a struct slice", f.GoName)
	}
	diagKey := scope.diagKey(full)
	entry := fmt.Sprintf("ta%d", scope.depth+1)
	index := fmt.Sprintf("i%d", scope.depth+1)
	fmt.Fprintf(b, "\tif %s, ok := %s.Get(%q); ok {\n", entry, scope.src, full)
	fmt.Fprintf(b, "\t\tif !%s.IsTables {\n", entry)
	fmt.Fprintf(b, "\t\t\treturn fmt.Errorf(\"configbind: %s: expected an array of tables ([[%s]])\"%s)\n",
		diagKey, diagKey, doubledDiagArgs(scope))
	b.WriteString("\t\t}\n")
	fmt.Fprintf(b, "\t\t%s = make([]%s, len(%s.Tables))\n", access, f.ElemType, entry)
	fmt.Fprintf(b, "\t\tfor %s := range %s.Tables {\n", index, entry)
	elemScope := applyScope{
		src: fmt.Sprintf("%s.Tables[%s]", entry, index),
		// The element's index joins the key here, so every diagnostic emitted
		// inside the loop names which element it came from.
		diagPrefix:    diagKey + "[%d]",
		diagIndexArgs: append(append([]string(nil), scope.diagIndexArgs...), index),
		depth:         scope.depth + 1,
	}
	if err := emitApplyFields(b, elemScope, fmt.Sprintf("%s[%s]", access, index), "", f.Nested); err != nil {
		return err
	}
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	return nil
}

func collectKeys(prefix string, fields []Field) []string {
	var keys []string
	var walk func(string, []Field)
	walk = func(p string, fs []Field) {
		for _, f := range fs {
			full := joinKey(p, f.Key)
			switch f.Kind {
			case FieldStruct:
				walk(full, f.Nested)
			case FieldStructSlice:
				// The array itself is one key; its element keys are per element.
				keys = append(keys, full)
			default:
				keys = append(keys, full)
			}
		}
	}
	walk(prefix, fields)
	return keys
}

// knownFieldKinds indexes every Bind key emitted in this generation run by kind.
// knownFalsyChoices is the run's falsy map, which a dependon check needs when
// the parent it names lives in another spec of the same run.
func knownFalsyChoices(specs []Spec) (map[string]string, error) {
	out := map[string]string{}
	for _, spec := range specs {
		if spec.SubCommand {
			continue
		}
		falsy, err := collectFalsy(spec.Prefix, spec.Fields)
		if err != nil {
			return nil, err
		}
		for key, value := range falsy {
			out[key] = value
		}
	}
	return out, nil
}

func knownFieldKinds(specs []Spec) map[string]FieldKind {
	known := map[string]FieldKind{}
	for _, spec := range specs {
		if spec.SubCommand {
			continue
		}
		for _, field := range flattenFields(spec.Prefix, spec.Fields) {
			known[field.Key] = field.Field.Kind
		}
	}
	return known
}

// knownEnumChoices is the run's enum map, which a dependon value check reads to
// tell a real choice of the parent from a typo. knownIntTypes carries the Go type
// an int parent is assigned as, so a value is parsed at the parent's own width.
// Both are keyed like knownFieldKinds and share its blind spot: a parent bound in
// another package is absent, and its values go unchecked.
func knownEnumChoices(specs []Spec) map[string]string {
	out := map[string]string{}
	for _, spec := range specs {
		if spec.SubCommand {
			continue
		}
		for _, field := range flattenFields(spec.Prefix, spec.Fields) {
			if field.Field.Enum != "" {
				out[field.Key] = field.Field.Enum
			}
		}
	}
	return out
}

func knownIntTypes(specs []Spec) map[string]string {
	out := map[string]string{}
	for _, spec := range specs {
		if spec.SubCommand {
			continue
		}
		for _, field := range flattenFields(spec.Prefix, spec.Fields) {
			if field.Field.Kind == FieldInt {
				out[field.Key] = field.Field.GoType
			}
		}
	}
	return out
}

// collectDependsOn maps each dependent key to every condition it answers to: the
// key's own dependon tag plus the tags of the structs it sits under. It rejects
// the mistakes visible at generation time; a parent that belongs to another
// package is absent from known and its kind, values, and enum go unchecked.
func collectDependsOn(prefix string, fields []Field, known map[string]FieldKind, falsy, enums map[string]string, intTypes map[string]string) (map[string][]dependency, error) {
	out := map[string][]dependency{}
	for _, field := range flattenFields(prefix, fields) {
		for _, condition := range field.Parents {
			if err := checkDependency(condition, field.Key, known, falsy, enums, intTypes); err != nil {
				return nil, err
			}
			out[field.Key] = appendParent(out[field.Key], condition)
		}
	}
	if err := checkDependencyCycles(out); err != nil {
		return nil, err
	}
	return out, nil
}

// checkDependency rejects one condition an author cannot have meant.
func checkDependency(condition dependency, key string, known map[string]FieldKind, falsy, enums map[string]string, intTypes map[string]string) error {
	owner, parent := condition.Owner, condition.Key
	switch {
	case parent == "":
		return fmt.Errorf("field %s: dependon needs a parent key before the operator", owner)
	case strings.Contains(parent, ","):
		return fmt.Errorf("field %s: dependon takes one parent key, got %q", owner, parent)
	case parent == key:
		return fmt.Errorf("field %s: dependon refers to itself", owner)
	}
	if err := checkDependencyValues(condition, known, enums, intTypes); err != nil {
		return err
	}
	return checkParentKind(condition, known, falsy)
}

// checkDependencyValues rejects a value list that cannot select anything. A value
// is checked against the parent's kind, and against its enum allowlist when the
// parent declares one in this run: a mistyped choice would otherwise hide a whole
// subtree for good, which is the one failure this feature can cause and the one no
// reader can diagnose from the output.
func checkDependencyValues(condition dependency, known map[string]FieldKind, enums map[string]string, intTypes map[string]string) error {
	owner, parent := condition.Owner, condition.Key
	if condition.Op == "" {
		return nil
	}
	seen := make(map[string]bool, len(condition.Values))
	for _, value := range condition.Values {
		switch {
		case value == "":
			return fmt.Errorf("field %s: dependon %s%s names an empty value", owner, parent, condition.Op)
		case seen[value]:
			return fmt.Errorf("field %s: dependon %s%s names %q twice", owner, parent, condition.Op, value)
		}
		seen[value] = true
		// A parent this run cannot see has no kind of its own, and FieldString
		// happens to be the zero value; checking that explicitly keeps a future
		// reordering of the kinds from validating a foreign value as a bool.
		if kind, ok := known[parent]; ok {
			if err := checkDependencyValueKind(owner, parent, value, kind, intTypes[parent]); err != nil {
				return err
			}
		}
		if err := checkDependencyValueEnum(owner, parent, value, enums[parent]); err != nil {
			return err
		}
	}
	return nil
}

func checkDependencyValueKind(owner, parent, value string, kind FieldKind, goType string) error {
	switch kind {
	case FieldBool:
		if value != "true" && value != "false" {
			return fmt.Errorf("field %s: dependon parent %q is a bool, so %q is not a value it can hold", owner, parent, value)
		}
	case FieldInt:
		spec, err := codegen.IntFieldSpecOf(goType)
		if err != nil {
			return fmt.Errorf("field %s: %w", owner, err)
		}
		if _, err := spec.ParseLiteral(value); err != nil {
			return fmt.Errorf("field %s: dependon value %q is not a valid %s for parent %q: %w", owner, value, spec.Name, parent, err)
		}
	case FieldDuration:
		if _, err := time.ParseDuration(value); err != nil {
			return fmt.Errorf("field %s: dependon value %q is not a duration for parent %q: %w", owner, value, parent, err)
		}
	}
	return nil
}

func checkDependencyValueEnum(owner, parent, value, enum string) error {
	if enum == "" {
		return nil
	}
	for _, choice := range strings.Split(enum, ",") {
		if strings.TrimSpace(choice) == value {
			return nil
		}
	}
	return fmt.Errorf("field %s: dependon value %q is not one of the enum choices %q of parent %q", owner, value, enum, parent)
}

// checkParentKind states which kinds a parent may have. A string is empty when it
// is "", a bool when it is false; a number or duration has no such value of its
// own, because zero is a deliberate setting, so an emptiness test may only name
// one once its own falsy tag says which value means off. A condition that names
// its values inline has already said it and needs no falsy tag.
func checkParentKind(condition dependency, known map[string]FieldKind, falsy map[string]string) error {
	owner, parent := condition.Owner, condition.Key
	kind, ok := known[parent]
	if !ok {
		return nil
	}
	switch kind {
	case FieldString, FieldBool:
		return nil
	case FieldInt, FieldDuration:
		if condition.Op == "" && falsy[parent] == "" {
			return fmt.Errorf("field %s: dependon parent %q is a number or duration, so it needs its own falsy tag to say which value means off, or a value named in the tag", owner, parent)
		}
		return nil
	default:
		return fmt.Errorf("field %s: dependon parent %q must be a string, bool, int, or duration field", owner, parent)
	}
}

// renderDependency writes one condition as a composite literal. The emptiness
// form keeps the shortest spelling it had as a bare string, so the common tag
// stays readable in the generated file.
func renderDependency(condition dependency) string {
	if condition.Op == "" {
		return fmt.Sprintf("{Key: %s}", strconv.Quote(condition.Key))
	}
	quoted := make([]string, 0, len(condition.Values))
	for _, value := range condition.Values {
		quoted = append(quoted, strconv.Quote(value))
	}
	return fmt.Sprintf("{Key: %s, Op: %s, Values: []string{%s}}",
		strconv.Quote(condition.Key), strconv.Quote(condition.Op), strings.Join(quoted, ", "))
}

// appendParent keeps one condition per parent and operator. A leaf that repeats
// an ancestor's exact condition gains nothing by holding it twice.
func appendParent(parents []dependency, condition dependency) []dependency {
	for _, existing := range parents {
		if existing.Key == condition.Key && existing.Op == condition.Op && slices.Equal(existing.Values, condition.Values) {
			return parents
		}
	}
	return append(parents, condition)
}

// collectFalsy maps each falsy-tagged key to the choice that means "off". A
// string names one of its own enum choices; a number or duration names the
// zero-ish value that disables the feature it configures. Bool is excluded
// because false already says it, and so are the kinds with no single value.
func collectFalsy(prefix string, fields []Field) (map[string]string, error) {
	out := map[string]string{}
	for _, field := range flattenFields(prefix, fields) {
		value := field.Field.Falsy
		if value == "" {
			continue
		}
		if field.Field.Kind == FieldStruct || field.Field.Kind == FieldStructSlice {
			// checkStructFieldTags owns placement and words the rejection in terms
			// of where the tag sits; reporting it here would preempt that with a
			// message about value kinds instead.
			continue
		}
		switch field.Field.Kind {
		case FieldString:
		case FieldInt:
			spec, err := codegen.IntFieldSpecOf(field.Field.GoType)
			if err != nil {
				return nil, fmt.Errorf("field %s: %w", field.Field.GoName, err)
			}
			if _, err := spec.ParseLiteral(value); err != nil {
				return nil, fmt.Errorf("field %s: falsy %q is not a valid %s: %w", field.Field.GoName, value, spec.Name, err)
			}
		case FieldDuration:
			if _, err := time.ParseDuration(value); err != nil {
				return nil, fmt.Errorf("field %s: falsy %q is not a duration: %w", field.Field.GoName, value, err)
			}
		default:
			return nil, fmt.Errorf("field %s: falsy applies to string, int, and duration fields only", field.Field.GoName)
		}
		out[field.Key] = value
	}
	return out, nil
}

// modeEntry is one key and the mode that applies to it, kept in declaration
// order so the generated map literal is deterministic.
type modeEntry struct {
	Key  string
	Mode string
}

// collectSecrets lists every key with a disclosure mode.
func collectSecrets(prefix string, fields []Field) ([]modeEntry, error) {
	return collectInheritedModes(prefix, fields, func(f Field) string { return f.Secret }, checkSecretMode)
}

// collectSummary lists every key rated as detail. It shares collectSecrets' walk
// because it shares its shape exactly: a rating covers a subtree, and an element
// field carries one under the same stable path.
func collectSummary(prefix string, fields []Field) ([]modeEntry, error) {
	return collectInheritedModes(prefix, fields, func(f Field) string { return f.Summary }, checkSummaryMode)
}

// collectInheritedModes lists every key a per-key mode applies to, in
// declaration order: leaves, the keys that inherit a mode from a struct or array
// above them, and the fields of array-of-tables elements.
//
// An element field is indexed by its path under the array key rather than by its
// own key, because its own key carries an index that only exists at run time.
// Provenance matches that path at every index.
func collectInheritedModes(prefix string, fields []Field, read func(Field) string, check func(string, string) error) ([]modeEntry, error) {
	var out []modeEntry
	var walk func(string, []Field, string) error
	walk = func(p string, fs []Field, inherited string) error {
		for _, field := range fs {
			key := joinKey(p, field.Key)
			mode := inherited
			if own := read(field); own != "" {
				if err := check(field.GoName, own); err != nil {
					return err
				}
				mode = own
			}
			if mode != "" {
				out = append(out, modeEntry{Key: key, Mode: mode})
			}
			switch field.Kind {
			case FieldStruct, FieldStructSlice:
				if err := walk(key, field.Nested, mode); err != nil {
					return err
				}
			}
		}
		return nil
	}
	if err := walk(prefix, fields, ""); err != nil {
		return nil, err
	}
	return out, nil
}

func checkSecretMode(goName, mode string) error {
	switch mode {
	case "hide", "mask", "show":
		return nil
	}
	return fmt.Errorf("field %s: secret must be hide, mask, or show, got %q", goName, mode)
}

// checkSummaryMode admits only omit. There is no "show" counterpart, because an
// untagged key is already shown everywhere; a second mode would only be needed if
// the untagged default ever changed.
func checkSummaryMode(goName, mode string) error {
	if mode == summaryOmit {
		return nil
	}
	return fmt.Errorf("field %s: summary must be %s, got %q", goName, summaryOmit, mode)
}

// summaryOmit is the only summary rating, mirroring the configbind constant of
// the same value, which this package emits as text rather than importing.
const summaryOmit = "omit"

// checkDependencyCycles rejects a dependon chain that loops back on itself.
// Only same-run edges are visible, which is where an author-written cycle lives.
func checkDependencyCycles(edges map[string][]dependency) error {
	var walk func(key string, seen map[string]bool) error
	walk = func(key string, seen map[string]bool) error {
		for _, condition := range edges[key] {
			parent := condition.Key
			if seen[parent] {
				return fmt.Errorf("dependon cycle through %q", parent)
			}
			seen[parent] = true
			if err := walk(parent, seen); err != nil {
				return err
			}
			delete(seen, parent)
		}
		return nil
	}
	for start := range edges {
		if err := walk(start, map[string]bool{start: true}); err != nil {
			return err
		}
	}
	return nil
}

func collectDefaults(prefix string, fields []Field) map[string]string {
	out := map[string]string{}
	var walk func(string, []Field)
	walk = func(p string, fs []Field) {
		for _, f := range fs {
			full := joinKey(p, f.Key)
			switch f.Kind {
			case FieldStruct:
				walk(full, f.Nested)
			case FieldStructSlice:
				// Element defaults are applied per element inside the generated loop.
			default:
				if f.Default != "" {
					out[full] = f.Default
				}
			}
		}
	}
	walk(prefix, fields)
	return out
}

func collectFlagMetas(prefix string, fields []Field) []cliparser.FieldMeta {
	var out []cliparser.FieldMeta
	var walk func(string, []Field)
	walk = func(p string, fs []Field) {
		for _, f := range fs {
			full := joinKey(p, f.Key)
			// relative key under original prefix for cliparser FieldMeta
			rel := strings.TrimPrefix(full, prefix+".")
			if full == prefix {
				rel = ""
			}
			if f.Kind == FieldStruct {
				walk(full, f.Nested)
				continue
			}
			if f.Kind == FieldStructSlice {
				// No flag or env var can address a repeated table.
				continue
			}
			if f.Arg != "" {
				continue
			}
			// FieldMeta uses Prefix + Key where Key is relative path under prefix
			key := strings.TrimPrefix(full, prefix+".")
			m := cliparser.FieldMeta{
				Prefix: prefix,
				Key:    key,
				Opt:    f.Opt,
				Env:    f.Env,
				Help:   f.Help,
			}
			switch f.Kind {
			case FieldBool:
				m.Kind = cliparser.KindBool
			case FieldStringSlice:
				m.Kind = cliparser.KindArray
			default:
				m.Kind = cliparser.KindString
			}
			_ = rel
			out = append(out, m)
		}
	}
	walk(prefix, fields)
	return out
}

func joinKey(prefix, key string) string {
	if prefix == "" {
		return key
	}
	if key == "" {
		return prefix
	}
	return prefix + "." + key
}
