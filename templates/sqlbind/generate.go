package sqlbind

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"strconv"
	"strings"
	"unicode"
)

// Dialect names a supported target database. It is the single generation-time
// value carrying every engine difference, so a target is chosen once instead of
// per facet.
const (
	DialectPostgreSQL = "postgresql"
	DialectMySQL      = "mysql"
	DialectSQLite     = "sqlite"
)

// SupportedDialects lists every accepted Dialect value, in the order error
// messages report them.
var SupportedDialects = []string{DialectPostgreSQL, DialectMySQL, DialectSQLite}

// placeholderStyles maps each supported dialect to the runtime PlaceholderStyle
// constant it emits. It is also the set ValidateDialect accepts, so a dialect
// cannot be added without choosing a style for it. SQLite reads several
// placeholder forms; ? is the positional one, matching how arguments are bound.
var placeholderStyles = map[string]string{
	DialectPostgreSQL: "Dollar",
	DialectMySQL:      "Question",
	DialectSQLite:     "Question",
}

// ValidateDialect reports whether name selects a supported database. It is
// exported so a caller discovering SQL templates can reject a missing or
// unknown dialect as a configuration error, before generating anything.
func ValidateDialect(name string) error {
	if _, ok := placeholderStyles[name]; ok {
		return nil
	}
	if name == "" {
		return fmt.Errorf("no SQL dialect selected; choose one of %s", strings.Join(SupportedDialects, ", "))
	}
	return fmt.Errorf("unsupported SQL dialect %q; choose one of %s", name, strings.Join(SupportedDialects, ", "))
}

// GenerateOptions controls SQL code generation.
type GenerateOptions struct {
	Package string
	// Dialect selects the target database. It is required: there is no implicit
	// default, because a silently assumed dialect emits placeholders the target
	// engine rejects.
	Dialect string
	// ContextAPI adds <Component>Context wrappers which resolve an executor
	// from context.Context while preserving the explicit executor APIs.
	ContextAPI bool
	// ContextOnly publishes the Context-resolved function under the declared
	// component name and makes the executor-taking function unexported. It
	// implies ContextAPI and generates no <Component>Context wrapper.
	ContextOnly bool
	// ExecutorResolver selects a framework-specific Context resolver. A nil
	// resolver uses sqlbind.SQLExecutorFromContext. Setting it implies ContextAPI.
	ExecutorResolver *ExecutorResolver
}

// ExecutorResolver identifies a package function with the signature
// func(context.Context) (SQLExecutor, error).
type ExecutorResolver struct {
	PackagePath string
	Name        string
}

// Generate parses, validates, and compiles a SQL template module to Go.
func Generate(filename string, source []byte, options GenerateOptions) ([]byte, error) {
	module, err := Parse(filename, source)
	if err != nil {
		return nil, err
	}
	c := newCompiler(filename, module)
	if err := c.analyze(); err != nil {
		return nil, err
	}
	if err := ValidateDialect(options.Dialect); err != nil {
		return nil, err
	}
	if options.ExecutorResolver != nil {
		if options.ExecutorResolver.PackagePath == "" || !token.IsIdentifier(options.ExecutorResolver.Name) || !unicode.IsUpper([]rune(options.ExecutorResolver.Name)[0]) {
			return nil, fmt.Errorf("invalid SQL executor resolver %q.%q", options.ExecutorResolver.PackagePath, options.ExecutorResolver.Name)
		}
		options.ContextAPI = true
	}
	if options.ContextOnly {
		options.ContextAPI = true
	}
	generated, err := c.emit(options)
	if err != nil {
		return nil, err
	}
	formatted, err := format.Source(generated)
	if err != nil {
		return generated, fmt.Errorf("format generated SQL code: %w\n%s", err, generated)
	}
	return formatted, nil
}

type goEmitter struct {
	c           *compiler
	b           bytes.Buffer
	indent      int
	dialect     string
	contextAPI  bool
	contextOnly bool
	resolver    *ExecutorResolver
}

func (c *compiler) emit(options GenerateOptions) ([]byte, error) {
	e := &goEmitter{c: c, dialect: options.Dialect, contextAPI: options.ContextAPI, contextOnly: options.ContextOnly, resolver: options.ExecutorResolver}
	if e.contextAPI && !e.contextOnly {
		for _, statement := range c.statements {
			if statement.decl.Exported && statement.cardinality != "predicate" && statement.cardinality != "relation" && c.nameExists(statement.decl.Name+"Context") {
				return nil, c.error(statement.decl.Pos, "generated Context API conflicts with declaration "+statement.decl.Name+"Context")
			}
		}
	}
	pkg := options.Package
	if pkg == "" && c.module.Package != nil {
		pkg = c.module.Package.Name
		if i := strings.LastIndex(pkg, "."); i >= 0 {
			pkg = pkg[i+1:]
		}
	}
	if pkg == "" {
		pkg = "templates"
	}
	pkg = goIdentifier(pkg)
	e.b.WriteString("// Code generated by tinybind SQL templates; DO NOT EDIT.\n\n")
	fmt.Fprintf(&e.b, "package %s\n\n", pkg)
	e.emitImports()
	e.emitDeclaredTypes()
	for _, declaration := range c.module.Declarations {
		if statement, ok := declaration.(*TemplateDecl); ok {
			if err := e.emitStatement(statement); err != nil {
				return nil, err
			}
		}
	}
	return e.b.Bytes(), nil
}

func (e *goEmitter) emitImports() {
	executable := false
	many := false
	atMostOne := false
	// The executor interfaces moved to the runtime package, so database/sql is
	// referenced only where a generated signature or value still names it:
	// sql.Result for exec and sql.ErrNoRows for one.
	databaseSQL := false
	for _, s := range e.c.statements {
		if !s.decl.Exported || s.cardinality == "predicate" || s.cardinality == "relation" {
			continue
		}
		executable = true
		switch s.cardinality {
		case "many":
			many = true
		case "one":
			atMostOne = true
			databaseSQL = true
		case "optional":
			atMostOne = true
		case "exec":
			databaseSQL = true
		}
	}
	e.b.WriteString("import (\n")
	if executable {
		e.b.WriteString("\t\"context\"\n")
	}
	if databaseSQL {
		e.b.WriteString("\t\"database/sql\"\n")
	}
	if atMostOne {
		e.b.WriteString("\t\"fmt\"\n")
	}
	if many {
		e.b.WriteString("\t\"iter\"\n")
	}
	if e.c.usesKind(kindURL) {
		e.b.WriteString("\t\"net/url\"\n")
	}
	if e.c.usesKind(kindDateTime) || e.c.usesKind(kindDate) || e.c.usesKind(kindTime) {
		e.b.WriteString("\t\"time\"\n")
	}
	// The statement builder, Statement, and executor interfaces live in the
	// module, so any statement at all needs the runtime package.
	if len(e.c.statements) > 0 {
		fmt.Fprintf(&e.b, "\t%s %q\n", runtimeAlias, runtimePackage)
	}
	if e.hasContextAPI() && e.resolver != nil {
		fmt.Fprintf(&e.b, "\t_tinybindresolver %q\n", e.resolver.PackagePath)
	}
	e.b.WriteString(")\n\n")
}

const (
	runtimeAlias   = "_tinybindsql"
	runtimePackage = "github.com/shibukawa/tinybind-go/sqlbind"
)

// runtime qualifies a name in the module SQL runtime package. Generated code
// declares no runtime of its own.
func runtime(name string) string { return runtimeAlias + "." + name }

// builderStyle names the PlaceholderStyle constant for the dialect chosen at
// generation time. The placeholder token is the only dialect difference the
// generator emits; author SQL text reaches the output verbatim. Generate
// validated the dialect, so an unmapped one would emit uncompilable code rather
// than quietly fall back to another engine's placeholders.
func (e *goEmitter) builderStyle() string {
	return runtime(placeholderStyles[e.dialect])
}

func (e *goEmitter) hasContextAPI() bool {
	if !e.contextAPI {
		return false
	}
	for _, statement := range e.c.statements {
		if statement.decl.Exported && statement.cardinality != "predicate" && statement.cardinality != "relation" {
			return true
		}
	}
	return false
}

// executorAPIName names the function that takes an explicit executor.
// Context-only mode makes it unexported so the declared component name can
// carry the Context-resolved public API instead.
func (e *goEmitter) executorAPIName(name string) string {
	if e.contextOnly {
		return "_tinybindExec" + name
	}
	return name
}

// contextAPIName names the Context-resolved function.
func (e *goEmitter) contextAPIName(name string) string {
	if e.contextOnly {
		return name
	}
	return name + "Context"
}

// resolverCall selects the Context resolver for one statement. A write
// statement uses the resolver that rejects a read-only executor, unless a
// framework resolver is configured: that contract carries no access mode, so
// the check is unavailable there.
func (e *goEmitter) resolverCall(statement string, readOnly bool) string {
	if e.resolver != nil {
		return "_tinybindresolver." + e.resolver.Name + "(ctx)"
	}
	if readOnly {
		return runtime("SQLExecutorFromContext") + "(ctx)"
	}
	return fmt.Sprintf("%s(ctx, %q)", runtime("WriteExecutorFromContext"), statement)
}

func (e *goEmitter) emitDeclaredTypes() {
	for _, declaration := range e.c.module.Declarations {
		switch d := declaration.(type) {
		case *TypeDecl:
			fmt.Fprintf(&e.b, "type %s struct {\n", d.Name)
			for _, f := range d.Fields {
				t, _ := e.c.resolveType(f.Type)
				fmt.Fprintf(&e.b, "\t%s %s\n", goPublicName(f.Name), goType(t))
			}
			e.b.WriteString("}\n\n")
		case *EnumDecl:
			fmt.Fprintf(&e.b, "type %s string\n\nconst (\n", d.Name)
			for _, m := range d.Members {
				fmt.Fprintf(&e.b, "\t%s%s %s = %q\n", d.Name, m.Name, d.Name, m.Name)
			}
			e.b.WriteString(")\n\n")
		}
	}
}

func (e *goEmitter) emitStatement(statement *TemplateDecl) error {
	info := e.c.statements[statement.Name]
	internal := "_tinybindBuild" + statement.Name
	fmt.Fprintf(&e.b, "func %s(b *%s", internal, runtime("Builder"))
	for _, p := range statement.Parameters {
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, ", %s %s", goLocalName(p.Name), goType(t))
	}
	e.b.WriteString(") error {\n")
	e.indent = 1
	if err := e.emitNodes(statement.Body.([]Node), info.params); err != nil {
		return err
	}
	e.line("return nil")
	e.b.WriteString("}\n\n")
	if !statement.Exported {
		return nil
	}
	fmt.Fprintf(&e.b, "func Build%s(", statement.Name)
	e.emitParams(statement.Parameters)
	fmt.Fprintf(&e.b, ") (%s, error) {\n\tb := %s(%s)\n\tif err := %s(&b", runtime("Statement"), runtime("NewBuilder"), e.builderStyle(), internal)
	for _, p := range statement.Parameters {
		e.b.WriteString(", " + goLocalName(p.Name))
	}
	fmt.Fprintf(&e.b, "); err != nil { return %s{}, err }\n", runtime("Statement"))
	e.b.WriteString("\treturn b.Statement(), nil\n}\n\n")
	switch info.cardinality {
	case "exec":
		e.emitExecAPI(statement)
	case "one", "optional", "many":
		e.emitQueryAPI(statement, info)
	}
	if e.contextAPI && info.cardinality != "predicate" && info.cardinality != "relation" {
		e.emitContextAPI(statement, info)
	}
	return nil
}

func (e *goEmitter) emitParams(params []Parameter) {
	for i, p := range params {
		if i > 0 {
			e.b.WriteString(", ")
		}
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, "%s %s", goLocalName(p.Name), goType(t))
	}
}
func (e *goEmitter) callParams(params []Parameter) string {
	var out []string
	for _, p := range params {
		out = append(out, goLocalName(p.Name))
	}
	if len(out) == 0 {
		return ""
	}
	return ", " + strings.Join(out, ", ")
}

func (e *goEmitter) emitExecAPI(statement *TemplateDecl) {
	fmt.Fprintf(&e.b, "func %s(ctx context.Context, db %s", e.executorAPIName(statement.Name), runtime("Execer"))
	for _, p := range statement.Parameters {
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, ", %s %s", goLocalName(p.Name), goType(t))
	}
	e.b.WriteString(") (sql.Result, error) {\n")
	fmt.Fprintf(&e.b, "\tstatement, err := Build%s(%s)\n", statement.Name, strings.TrimPrefix(e.callParams(statement.Parameters), ", "))
	e.b.WriteString("\tif err != nil { return nil, err }\n\treturn db.ExecContext(ctx, statement.SQL, statement.Args...)\n}\n\n")
}

func (e *goEmitter) emitQueryAPI(statement *TemplateDecl, info *statementInfo) {
	result := goType(info.result)
	if info.cardinality == "many" {
		e.emitManyAPI(statement, info, result)
		return
	}
	returnType := result
	if info.cardinality == "optional" {
		returnType = "*" + result
	}
	fmt.Fprintf(&e.b, "func %s(ctx context.Context, db %s", e.executorAPIName(statement.Name), runtime("Querier"))
	for _, p := range statement.Parameters {
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, ", %s %s", goLocalName(p.Name), goType(t))
	}
	fmt.Fprintf(&e.b, ") (%s, error) {\n", returnType)
	fmt.Fprintf(&e.b, "\tstatement, err := Build%s(%s)\n", statement.Name, strings.TrimPrefix(e.callParams(statement.Parameters), ", "))
	zero := result + "{}"
	if info.cardinality == "optional" {
		zero = "nil"
	}
	fmt.Fprintf(&e.b, "\tif err != nil { return %s, err }\n", zero)
	e.b.WriteString("\trows, err := db.QueryContext(ctx, statement.SQL, statement.Args...)\n")
	fmt.Fprintf(&e.b, "\tif err != nil { return %s, err }\n\tdefer rows.Close()\n", zero)
	fmt.Fprintf(&e.b, "\tif !rows.Next() { if err := rows.Err(); err != nil { return %s, err }; ", zero)
	if info.cardinality == "one" {
		fmt.Fprintf(&e.b, "return %s, sql.ErrNoRows", zero)
	} else {
		e.b.WriteString("return nil, nil")
	}
	e.b.WriteString(" }\n")
	fmt.Fprintf(&e.b, "\tvar result %s\n", result)
	e.emitScan("\t", info.result, "result", zero)
	fmt.Fprintf(&e.b, "\tif rows.Next() { return %s, fmt.Errorf(\"tinybind SQL: %s expected at most one row\") }\n", zero, statement.Name)
	fmt.Fprintf(&e.b, "\tif err := rows.Err(); err != nil { return %s, err }\n", zero)
	if info.cardinality == "optional" {
		e.b.WriteString("\treturn &result, nil\n}\n\n")
	} else {
		e.b.WriteString("\treturn result, nil\n}\n\n")
	}
}

func (e *goEmitter) emitManyAPI(statement *TemplateDecl, info *statementInfo, result string) {
	fmt.Fprintf(&e.b, "func %s(ctx context.Context, db %s", e.executorAPIName(statement.Name), runtime("Querier"))
	for _, p := range statement.Parameters {
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, ", %s %s", goLocalName(p.Name), goType(t))
	}
	fmt.Fprintf(&e.b, ") iter.Seq2[%s, error] {\n", result)
	fmt.Fprintf(&e.b, "\treturn func(yield func(%s, error) bool) {\n", result)
	fmt.Fprintf(&e.b, "\t\tstatement, err := Build%s(%s)\n", statement.Name, strings.TrimPrefix(e.callParams(statement.Parameters), ", "))
	fmt.Fprintf(&e.b, "\t\tif err != nil { yield(%s{}, err); return }\n", result)
	e.b.WriteString("\t\trows, err := db.QueryContext(ctx, statement.SQL, statement.Args...)\n")
	fmt.Fprintf(&e.b, "\t\tif err != nil { yield(%s{}, err); return }\n\t\tdefer rows.Close()\n", result)
	fmt.Fprintf(&e.b, "\t\tfor rows.Next() {\n\t\t\tvar result %s\n", result)
	fmt.Fprintf(&e.b, "\t\t\tif err := rows.Scan(%s); err != nil { yield(%s{}, err); return }\n", e.scanArgs(info.result, "result"), result)
	e.b.WriteString("\t\t\tif !yield(result, nil) { return }\n\t\t}\n")
	fmt.Fprintf(&e.b, "\t\tif err := rows.Err(); err != nil { yield(%s{}, err) }\n", result)
	e.b.WriteString("\t}\n}\n\n")
}

func (e *goEmitter) emitContextAPI(statement *TemplateDecl, info *statementInfo) {
	name := e.contextAPIName(statement.Name)
	result := goType(info.result)
	fmt.Fprintf(&e.b, "func %s(ctx context.Context", name)
	for _, p := range statement.Parameters {
		t, _ := e.c.resolveType(p.Type)
		fmt.Fprintf(&e.b, ", %s %s", goLocalName(p.Name), goType(t))
	}
	if info.cardinality == "many" {
		fmt.Fprintf(&e.b, ") iter.Seq2[%s, error] {\n", result)
		fmt.Fprintf(&e.b, "\treturn func(yield func(%s, error) bool) {\n", result)
		fmt.Fprintf(&e.b, "\t\texecutor, err := %s\n", e.resolverCall(statement.Name, info.readOnly))
		fmt.Fprintf(&e.b, "\t\tif err != nil { yield(%s{}, err); return }\n", result)
		fmt.Fprintf(&e.b, "\t\tfor value, err := range %s(ctx, executor%s) {\n", e.executorAPIName(statement.Name), e.callParams(statement.Parameters))
		e.b.WriteString("\t\t\tif !yield(value, err) { return }\n\t\t}\n\t}\n}\n\n")
		return
	}

	returnType := "sql.Result"
	zero := "nil"
	if info.cardinality == "one" {
		returnType = result
		zero = result + "{}"
	} else if info.cardinality == "optional" {
		returnType = "*" + result
	}
	fmt.Fprintf(&e.b, ") (%s, error) {\n", returnType)
	fmt.Fprintf(&e.b, "\texecutor, err := %s\n", e.resolverCall(statement.Name, info.readOnly))
	fmt.Fprintf(&e.b, "\tif err != nil { return %s, err }\n", zero)
	fmt.Fprintf(&e.b, "\treturn %s(ctx, executor%s)\n}\n\n", e.executorAPIName(statement.Name), e.callParams(statement.Parameters))
}

func (e *goEmitter) emitScan(indent string, t valueType, target, zero string) {
	fmt.Fprintf(&e.b, "%sif err := rows.Scan(%s); err != nil { return %s, err }\n", indent, e.scanArgs(t, target), zero)
}

func (e *goEmitter) scanArgs(t valueType, target string) string {
	record := e.c.records[t.name]
	var fields []string
	for _, f := range record.Fields {
		address := "&" + target + "." + goPublicName(f.Name)
		// database/sql cannot assign a text column into a struct, so a url
		// field is scanned through a runtime adapter rather than its address.
		if field, err := e.c.resolveType(f.Type); err == nil && field.kind == kindURL {
			if field.optional {
				address = runtime("ScanOptionalURL") + "(" + address + ")"
			} else {
				address = runtime("ScanURL") + "(" + address + ")"
			}
		}
		fields = append(fields, address)
	}
	return strings.Join(fields, ", ")
}

func (e *goEmitter) emitNodes(nodes []Node, scope map[string]valueType) error {
	for _, node := range nodes {
		switch n := node.(type) {
		case *TextNode:
			e.line("b.WriteString(" + strconv.Quote(n.Text) + ")")
		case *ExpressionNode:
			code, err := e.expr(n.Expression, scope)
			if err != nil {
				return err
			}
			t := e.c.exprTypes[n.Expression]
			if t.kind == kindPredicate {
				call := n.Expression.(*CallExpr)
				id := call.Callee.(*IdentifierExpr)
				var args []string
				for _, argument := range call.Arguments {
					value, err := e.expr(argument, scope)
					if err != nil {
						return err
					}
					args = append(args, value)
				}
				suffix := ""
				if len(args) > 0 {
					suffix = ", " + strings.Join(args, ", ")
				}
				e.line("if err := _tinybindBuild" + id.Name + "(b" + suffix + "); err != nil { return err }")
			} else if t.kind == kindArray {
				if t.optional {
					return e.c.error(n.Pos, "optional arrays cannot be expanded as SQL values")
				}
				e.line("if err := " + runtime("AppendValues") + "(b, " + code + "); err != nil { return err }")
			} else {
				e.line("b.Arg(" + code + ")")
			}
		case *RelationNode:
			e.line("b.WriteByte('(')")
			var args []string
			for _, argument := range n.Arguments {
				value, err := e.expr(argument, scope)
				if err != nil {
					return err
				}
				args = append(args, value)
			}
			suffix := ""
			if len(args) > 0 {
				suffix = ", " + strings.Join(args, ", ")
			}
			e.line("if err := _tinybindBuild" + n.Name + "(b" + suffix + "); err != nil { return err }")
			e.line("b.WriteString(" + strconv.Quote(") AS "+n.Alias) + ")")
		case *IfNode:
			condition, err := e.expr(n.Condition, scope)
			if err != nil {
				return err
			}
			e.line("if " + condition + " {")
			e.indent++
			if err := e.emitNodes(n.Then, copyScope(scope)); err != nil {
				return err
			}
			e.indent--
			if len(n.Else) > 0 {
				e.line("} else {")
				e.indent++
				if err := e.emitNodes(n.Else, copyScope(scope)); err != nil {
					return err
				}
				e.indent--
				e.line("}")
			} else {
				e.line("}")
			}
		}
	}
	return nil
}

func (e *goEmitter) line(value string) {
	e.b.WriteString(strings.Repeat("\t", e.indent))
	e.b.WriteString(value)
	e.b.WriteByte('\n')
}
func (e *goEmitter) expr(expr Expr, scope map[string]valueType) (string, error) {
	switch x := expr.(type) {
	case *IdentifierExpr:
		if t, ok := e.c.enumMembers[x.Name]; ok {
			return t.name + x.Name, nil
		}
		return goLocalName(x.Name), nil
	case *LiteralExpr:
		switch x.ValueKind {
		case "string":
			return strconv.Quote(x.Value.(string)), nil
		case "bool":
			return strconv.FormatBool(x.Value.(bool)), nil
		case "number":
			return x.Value.(string), nil
		case "null":
			return "nil", nil
		}
	case *MemberExpr:
		o, err := e.expr(x.Object, scope)
		if err != nil {
			return "", err
		}
		return o + "." + goPublicName(x.Member), nil
	case *IndexExpr:
		o, err := e.expr(x.Object, scope)
		if err != nil {
			return "", err
		}
		i, err := e.expr(x.Index, scope)
		if err != nil {
			return "", err
		}
		return o + "[" + i + "]", nil
	case *CallExpr:
		id := x.Callee.(*IdentifierExpr)
		var args []string
		for _, a := range x.Arguments {
			code, err := e.expr(a, scope)
			if err != nil {
				return "", err
			}
			args = append(args, code)
		}
		return id.Name + "(" + strings.Join(args, ", ") + ")", nil
	case *UnaryExpr:
		o, err := e.expr(x.Operand, scope)
		if err != nil {
			return "", err
		}
		op := x.Operator
		if op == "not" {
			op = "!"
		}
		return op + "(" + o + ")", nil
	case *BinaryExpr:
		l, err := e.expr(x.Left, scope)
		if err != nil {
			return "", err
		}
		r, err := e.expr(x.Right, scope)
		if err != nil {
			return "", err
		}
		op := x.Operator
		if op == "and" {
			op = "&&"
		} else if op == "or" {
			op = "||"
		}
		return "(" + l + " " + op + " " + r + ")", nil
	case *ConditionalExpr:
		c, err := e.expr(x.Condition, scope)
		if err != nil {
			return "", err
		}
		a, err := e.expr(x.Then, scope)
		if err != nil {
			return "", err
		}
		b, err := e.expr(x.Else, scope)
		if err != nil {
			return "", err
		}
		return "(func() " + goType(e.c.exprTypes[expr]) + " { if " + c + " { return " + a + " }; return " + b + " })()", nil
	}
	return "", fmt.Errorf("unsupported expression %T", expr)
}

func goType(t valueType) string {
	var base string
	switch t.kind {
	case kindString, kindDecimal:
		base = "string"
	case kindBool:
		base = "bool"
	case kindInt:
		base = "int"
	case kindFloat:
		base = "float64"
	case kindBytes:
		base = "[]byte"
	case kindDateTime, kindDate, kindTime:
		base = "time.Time"
	case kindURL:
		base = "url.URL"
	case kindRecord, kindEnum:
		base = t.name
	case kindArray:
		if t.elem != nil {
			base = "[]" + goType(*t.elem)
		}
	}
	if t.optional {
		return "*" + base
	}
	return base
}
func goIdentifier(value string) string {
	var out strings.Builder
	for i, r := range value {
		if unicode.IsLetter(r) || r == '_' || (i > 0 && unicode.IsDigit(r)) {
			out.WriteRune(r)
		} else {
			out.WriteRune('_')
		}
	}
	if out.Len() == 0 {
		return "templates"
	}
	return goLocalName(out.String())
}
func goLocalName(name string) string {
	if goKeywords[name] {
		return "_" + name
	}
	return name
}
func goPublicName(name string) string {
	if name == "" {
		return name
	}
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

