package htmlbind

import (
	"crypto/sha256"
	"encoding/hex"
	"path/filepath"
	"strings"
)

// AssetKind classifies one extracted static file.
type AssetKind string

const (
	// AssetStyle is the stylesheet bundle of one generation unit.
	AssetStyle AssetKind = "style"
	// AssetScript is the script extracted from one component.
	AssetScript AssetKind = "script"
)

// DefaultPublicURLBase is the URL prefix used when a project configures none.
// Extraction always happens, so a zero-configuration project still gets working
// asset URLs.
const DefaultPublicURLBase = "/public/generated"

const (
	cssGeneratedHeader = "/* Code generated by tinybind templates; DO NOT EDIT. */\n"
	jsGeneratedHeader  = "// Code generated by tinybind templates; DO NOT EDIT.\n"
)

// Asset is one static file extracted from component head declarations. The
// content hash is part of the name, so a reference URL is immutably cacheable
// and identical input regenerates identical names and bytes.
type Asset struct {
	Kind AssetKind
	// Base is the file name without its extension.
	Base string
	// Extension is css for a stylesheet and js for a script, without a dot.
	Extension string
	Content   []byte
	// URL is the reference written into the emitted link or script tag.
	URL string
	// Owner names the component whose requirement:component-script-block
	// declared this file, and is empty for everything else. An empty owner is
	// document lifetime: the file evaluates once and is never released. A named
	// one binds the file to that component's live instances, which is the link
	// requirement:scoped-script-declaration publishes to a caller's runtime.
	Owner string
}

// FileName is the name the asset is written under, inside the configured
// public directory.
func (a Asset) FileName() string { return a.Base + "." + a.Extension }

// extractAssets moves style and inline script blocks out of the head
// contributions and into files, leaving each component a list of ready to
// write head tags. Styles bundle per generation unit, as
// decision:component-style-delivery requires; a script becomes its own file so
// the author attributes on its tag survive.
func (c *compiler) extractAssets(options GenerateOptions) ([]Asset, error) {
	unit := assetUnitName(options.Unit, c.filename)
	urlBase := options.PublicURLBase
	if urlBase == "" {
		urlBase = DefaultPublicURLBase
	}

	var assets []Asset
	styleURL := ""
	var styleAsset Asset
	if bundle := c.styleBundle(); bundle != "" {
		styleAsset = newAsset(AssetStyle, unit, cssGeneratedHeader+bundle, urlBase)
		assets = append(assets, styleAsset)
		styleURL = styleAsset.URL
	}

	seen := map[string]bool{}
	for _, component := range c.componentDecls() {
		info := c.components[component.Name]
		var tags []headTag
		var required []Asset
		for _, node := range info.head {
			if _, ok := node.(*TextNode); ok {
				continue
			}
			html := ""
			element, isElement := node.(*ElementNode)
			switch {
			case isElement && element.Name == "style":
				// An empty style block owns no bundle content, so it references
				// nothing.
				if strings.TrimSpace(info.style) == "" {
					continue
				}
				html = referenceTag("link", "href", styleURL, element.Attributes)
				required = append(required, styleAsset)
			case isElement && element.Name == "script" && inlineScript(element):
				body := strings.TrimSpace(elementText(element))
				asset := newAsset(AssetScript, unit, jsGeneratedHeader+body+"\n", urlBase)
				if !seen[asset.FileName()] {
					seen[asset.FileName()] = true
					assets = append(assets, asset)
				}
				html = referenceTag("script", "src", asset.URL, element.Attributes)
				required = append(required, asset)
			default:
				// A script or link already naming an external URL contributes
				// its tag unchanged and produces no file. It is already located,
				// so there is nothing for a caller to decide about it and it
				// joins no required set.
				html = renderStaticHTML([]Node{node})
			}
			if strings.TrimSpace(html) == "" {
				continue
			}
			tags = append(tags, headTag{html: html, source: c.headSource(info, node)})
		}
		// The component's own script block is extracted after its head
		// contributions so its reference tag follows them, which keeps a block
		// that calls into a head-declared script loading after it.
		if info.script != "" {
			content, extension, err := c.compileScriptBlock(info, component.Name, options)
			if err != nil {
				return nil, err
			}
			asset := newAsset(AssetScript, unit, jsGeneratedHeader+content+"\n", urlBase)
			if extension != "" {
				asset = asset.withExtension(extension, urlBase)
			}
			asset.Owner = component.Name
			if !seen[asset.FileName()] {
				seen[asset.FileName()] = true
				assets = append(assets, asset)
			}
			// The block is a module: a lifecycle method is an export, and a
			// classic script has no export surface to call one through. The lang
			// marker describes the authored block rather than the served file,
			// so it does not travel to the tag.
			attributes := append([]Attribute{{Kind: "html:attribute", Name: "type", Value: []AttributePart{{Kind: "html:text", Text: "module"}}}}, info.scriptAttributes...)
			tags = append(tags, headTag{html: referenceTag("script", "src", asset.URL, attributes)})
			required = append(required, asset)
		}
		info.headTags = tags
		info.assets = required
	}
	return assets, nil
}

// withExtension renames an asset to what a transform produced. The content hash
// is unchanged, because it names the bytes and the bytes did not change; only
// what the file is called does.
func (a Asset) withExtension(extension, urlBase string) Asset {
	a.Extension = extension
	a.URL = JoinPublicURL(urlBase, a.Base+"."+extension)
	return a
}

// compileScriptBlock hands a block marked with a lang attribute to the
// registered transform and returns what to write.
//
// A block with no marker is written as authored, which is every block until a
// project registers a hook.
func (c *compiler) compileScriptBlock(info *componentInfo, component string, options GenerateOptions) (string, string, error) {
	lang := ""
	var kept []Attribute
	for _, attribute := range info.scriptAttributes {
		if attribute.Name != "lang" {
			kept = append(kept, attribute)
			continue
		}
		// A lang marker is a build-time fact, so an expression there has
		// nothing to resolve against and reads as no marker at all.
		text, static := staticAttributeText(attribute)
		if !static {
			return "", "", c.error(info.scriptPos, "component "+component+" script block: lang must be written as literal text")
		}
		lang = strings.TrimSpace(text)
	}
	if lang == "" {
		return info.script, "", nil
	}
	info.scriptAttributes = kept
	hook, err := findContentHook(options.ContentHooks, lang)
	if err != nil {
		return "", "", c.error(info.scriptPos, "component "+component+" script block: "+err.Error())
	}
	result, err := hook.Transform(ContentRequest{
		Hook:      hook.Name,
		Lang:      lang,
		Content:   info.script,
		Component: component,
		Dir:       filepath.Dir(c.filename),
		File:      c.filename,
		Pos:       info.scriptPos,
	})
	if err != nil {
		return "", "", c.error(info.scriptPos, "component "+component+" script block: "+hook.Name+": "+err.Error())
	}
	extension := hook.Extension
	if result.Extension != "" {
		extension = result.Extension
	}
	c.contentReads = append(c.contentReads, result.Read...)
	return result.Content, extension, nil
}

// MediaType is what the reference tag says this asset is.
func (a Asset) MediaType() string {
	if a.Kind == AssetStyle {
		return "text/css"
	}
	return "text/javascript"
}

// styleBundle concatenates every already scoped component style of the module
// in declaration order, which keeps cascade order stable across generations.
func (c *compiler) styleBundle() string {
	var bundle strings.Builder
	for _, component := range c.componentDecls() {
		style := strings.TrimSpace(c.components[component.Name].style)
		if style == "" {
			continue
		}
		if bundle.Len() > 0 {
			bundle.WriteString("\n")
		}
		bundle.WriteString(style)
		bundle.WriteString("\n")
	}
	return bundle.String()
}

func (c *compiler) componentDecls() []*TemplateDecl {
	var components []*TemplateDecl
	for _, declaration := range c.module.Declarations {
		if component, ok := declaration.(*TemplateDecl); ok {
			components = append(components, component)
		}
	}
	return components
}

// inlineScript reports whether a head script carries content of its own rather
// than naming an external URL.
func inlineScript(element *ElementNode) bool {
	for _, attribute := range element.Attributes {
		if attribute.Name == "src" {
			return false
		}
	}
	return strings.TrimSpace(elementText(element)) != ""
}

func elementText(element *ElementNode) string {
	var text strings.Builder
	for _, child := range element.Children {
		if node, ok := child.(*TextNode); ok {
			text.WriteString(node.Text)
		}
	}
	return text.String()
}

// referenceTag builds the head tag pointing at an extracted file. Author
// attributes such as defer, async, and type are preserved; the style type
// attribute is dropped because it describes the block, not the link.
func referenceTag(name, urlAttribute, url string, attributes []Attribute) string {
	var out strings.Builder
	out.WriteString("<" + name)
	if name == "link" {
		out.WriteString(` rel="stylesheet"`)
	}
	out.WriteString(" " + urlAttribute + `="` + escapeAttributeValue(url) + `"`)
	for _, attribute := range attributes {
		if attribute.Name == urlAttribute || attribute.Name == "rel" {
			continue
		}
		if name == "link" && attribute.Name == "type" {
			continue
		}
		if attribute.Boolean {
			out.WriteString(" " + attribute.Name)
			continue
		}
		value, _ := staticAttributeText(attribute)
		out.WriteString(" " + attribute.Name + `="` + escapeAttributeValue(value) + `"`)
	}
	out.WriteString(">")
	if !voidElements[name] {
		out.WriteString("</" + name + ">")
	}
	return out.String()
}

// newAsset names a file after the generation unit, the asset kind, and the hash
// of its bytes, so an unchanged project regenerates identical names.
func newAsset(kind AssetKind, unit, content, urlBase string) Asset {
	extension := "css"
	if kind == AssetScript {
		extension = "js"
	}
	sum := sha256.Sum256([]byte(content))
	base := unit + "." + string(kind) + "." + hex.EncodeToString(sum[:])[:12]
	return Asset{
		Kind:      kind,
		Base:      base,
		Extension: extension,
		Content:   []byte(content),
		URL:       JoinPublicURL(urlBase, base+"."+extension),
	}
}

// JoinPublicURL appends a generated file name to the configured URL base. The
// base is used verbatim, so an absolute URL path and a full CDN URL behave the
// same and no path segment is ever inferred.
func JoinPublicURL(base, name string) string {
	return strings.TrimRight(base, "/") + "/" + name
}

// assetUnitName derives the generation unit name from the template path when a
// caller names none. Every separator is stripped, so a written asset cannot
// escape the configured public directory.
func assetUnitName(unit, filename string) string {
	if unit == "" {
		unit = filepath.Base(filename)
		if index := strings.Index(unit, "."); index > 0 {
			unit = unit[:index]
		}
	}
	var out strings.Builder
	for _, r := range unit {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_', r == '-':
			out.WriteRune(r)
		default:
			out.WriteRune('_')
		}
	}
	if out.Len() == 0 {
		return "templates"
	}
	return out.String()
}
